def _serializable_log_rows(rows):
    output = []
    for row in rows:
        item = {}
        for key, value in row.items():
            if isinstance(value, (list, tuple, dict)):
                item[key] = json.dumps(value, ensure_ascii=False)
            else:
                item[key] = value
        output.append(item)
    return output


