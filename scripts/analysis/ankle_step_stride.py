def load_ankle_positions(keypoints_npz, offsets_npz, fps):
    kps_data = np.load(keypoints_npz, allow_pickle=True)
    offsets_data = np.load(offsets_npz, allow_pickle=True)

    keypoints = kps_data["reconstruction"][0]
    valid_frames = np.asarray(kps_data["valid_frames"]).flatten().astype(int)
    offsets = offsets_data["offsets"]
    orig_frames = offsets_data["orig_frames"]
    cam_indices = (
        offsets_data["cam_indices"].astype(int)
        if "cam_indices" in offsets_data
        else np.zeros(len(orig_frames), dtype=int)
    )

    rows = []
    for i, offset_idx in enumerate(valid_frames):
        if offset_idx >= len(offsets) or i >= len(keypoints):
            continue

        frame_kps = keypoints[i]
        off_x, off_y = offsets[offset_idx]
        right = frame_kps[R_ANKLE]
        left = frame_kps[L_ANKLE]

        right_x, right_y = float(right[0] + off_x), float(right[1] + off_y)
        left_x, left_y = float(left[0] + off_x), float(left[1] + off_y)
        right_conf = float(right[2]) if len(right) > 2 else np.nan
        left_conf = float(left[2]) if len(left) > 2 else np.nan

        if right_y >= left_y:
            lower_foot = "right"
            lower_x, lower_y, lower_conf = right_x, right_y, right_conf
        else:
            lower_foot = "left"
            lower_x, lower_y, lower_conf = left_x, left_y, left_conf

        orig_frame = int(orig_frames[offset_idx])
        rows.append({
            "seq_frame": int(i),
            "offset_index": int(offset_idx),
            "orig_frame": orig_frame,
            "time_s": orig_frame / fps if fps > 0 else i / 60.0,
            "seq_time_s": i / fps if fps > 0 else i / 60.0,
            "cam": int(cam_indices[offset_idx]),
            "right_ankle_x": right_x,
            "right_ankle_y": right_y,
            "right_ankle_conf": right_conf,
            "left_ankle_x": left_x,
            "left_ankle_y": left_y,
            "left_ankle_conf": left_conf,
            "lower_foot": lower_foot,
            "lower_ankle_x": lower_x,
            "lower_ankle_y": lower_y,
            "lower_ankle_conf": lower_conf,
        })
    return rows


def load_foot_contact_positions(foot_npz, offsets_npz):
    """Load WholeBody heel/big-toe points in original-video coordinates.

    ``foot_keypoints.npz`` lives in the same tracked crop coordinates as the
    body keypoints.  The tracking offsets are therefore applied here, exactly
    as they are for ankle rows.  The returned mapping is keyed by sequential
    pose frame and by the already-corrected left/right foot identity.
    """
    if not foot_npz or not os.path.exists(foot_npz):
        return {}

    feet_data = np.load(foot_npz, allow_pickle=True)
    offsets_data = np.load(offsets_npz, allow_pickle=True)
    points = feet_data["keypoints"][0]
    scores = feet_data["scores"][0]
    valid_frames = np.asarray(feet_data["valid_frames"]).flatten().astype(int)
    offsets = offsets_data["offsets"]
    out = {}
    for seq_frame, offset_idx in enumerate(valid_frames):
        if seq_frame >= len(points) or offset_idx >= len(offsets):
            continue
        off_x, off_y = offsets[offset_idx]
        per_side = {}
        for side, indices in _FOOT_CONTACT_INDICES.items():
            per_side[side] = {}
            for joint, index in indices.items():
                point = points[seq_frame, index]
                score = float(scores[seq_frame, index])
                per_side[side][joint] = {
                    "x": float(point[0] + off_x),
                    "y": float(point[1] + off_y),
                    "conf": score,
                }
        out[int(seq_frame)] = per_side
    return out


def _runway_geometry(camera):
    """Build a normalized (along-track, cross-track) coordinate system.

    Skipped for homography-calibrated cameras even when start_line/end_line
    are present: those are synthesized from the two extreme (by world_x_m)
    calibration points purely so core/tracking.py's prescan/track_roi logic
    (which is tolerant, with pre_roll/end_roll buffers) behaves like the
    4-point mode. This quad's along-track band is much stricter (only ~8%
    overshoot allowed) and assumes start_line/end_line bound the full visible
    path -- for a long-jump camera the runner legitimately keeps moving past
    the last calibration marker (into the sand pit), so applying this check
    here would reject genuine contact points as "outside the runway".
    """
    if camera.get("homography_src_points"):
        return None
    start, end = camera.get("start_line"), camera.get("end_line")
    if not start or not end or len(start) != 2 or len(end) != 2:
        return None
    polygon = np.asarray([start[0], end[0], end[1], start[1]], dtype=np.float32)
    transform = cv2.getPerspectiveTransform(
        polygon, np.asarray([[0, 0], [1, 0], [1, 1], [0, 1]], dtype=np.float32))
    return {"polygon": polygon, "transform": transform}


def _runway_local(point, geometry):
    if geometry is None:
        return None
    pts = np.asarray([[[float(point[0]), float(point[1])]]], dtype=np.float32)
    return cv2.perspectiveTransform(pts, geometry["transform"])[0, 0]


# This small margin admits ordinary click/pose noise while rejecting a foot
# heatmap that has jumped well outside the calibrated ground strip.
HOMOGRAPHY_PHYSICAL_LATERAL_MARGIN_M = 0.15
HOMOGRAPHY_TEMPORAL_LATERAL_JUMP_M = 0.25
# Layer 2 (velocity continuity, see _recompute_contact_event_metrics()): a
# contact point can sit inside the physical runway yet still be a
# misdetection if it implies an impossible sprint speed to/from its
# neighbour. The absolute ceiling is comfortably above elite top speed
# (~12.4 m/s); the relative multiplier catches slower-but-still-implausible
# jumps relative to this specific trial's own pace.
HOMOGRAPHY_VELOCITY_ABS_CEILING_MPS = 13.0
HOMOGRAPHY_VELOCITY_RELATIVE_MULTIPLIER = 2.5


def _homography_lateral_matrix(camera):
    """Homography matrix for a homography-calibrated camera, or None."""
    src = camera.get("homography_src_points")
    dst = camera.get("homography_dst_world")
    if not src or not dst:
        return None
    try:
        calibration = _homography_calibration(src, dst)
    except ValueError:
        return None
    if calibration is None:
        return None
    return calibration["homography"]


def _homography_world_y(point, matrix):
    """Transform a pixel point to its homography world_y, or None."""
    if matrix is None:
        return None
    pts = np.asarray([[[float(point[0]), float(point[1])]]], dtype=np.float32)
    world = cv2.perspectiveTransform(pts, matrix)[0, 0]
    return float(world[1])


def _validate_homography_lateral(point, context):
    """Return (valid, world_y) for a pixel point's cross-track position.

    Checked against the session's own calibrated runway bounds (the six
    clicked control points' world_y span, plus a small margin for ordinary
    click/pose noise) -- not against a band learned from ankle position.
    A contact point (heel/toe) legitimately sits at a different world_y than
    the ankle in the same frame, so comparing a contact point's absolute
    position to an ankle-derived band rejected every contact point in
    trials where that offset was large. Temporal (frame-to-frame) speed
    plausibility is a separate check, in _recompute_contact_event_metrics()'s
    velocity-continuity pass.
    """
    matrix = (context or {}).get("homography_matrix")
    if matrix is None:
        return True, None
    world_y = _homography_world_y(point, matrix)
    physical_min = (context or {}).get("homography_world_y_min")
    physical_max = (context or {}).get("homography_world_y_max")
    if physical_min is None or physical_max is None:
        return True, world_y
    physical_ok = (
        float(physical_min) - HOMOGRAPHY_PHYSICAL_LATERAL_MARGIN_M
        <= world_y
        <= float(physical_max) + HOMOGRAPHY_PHYSICAL_LATERAL_MARGIN_M
    )
    return physical_ok, world_y


def _contact_validation_contexts(cameras, step_events, rows_by_seq, foot_contacts_by_seq):
    """Learn per-camera runway ground bands and foot/ankle size limits."""
    homography_matrices = {index: _homography_lateral_matrix(camera) for index, camera in enumerate(cameras)}
    contexts = {
        index: {"geometry": _runway_geometry(camera),
                "homography_matrix": homography_matrices[index],
                "ground_values": [],
                "attachment_samples": {"heel": [], "big_toe": []}}
        for index, camera in enumerate(cameras)
    }
    for index, camera in enumerate(cameras):
        dst = camera.get("homography_dst_world") or []
        try:
            ys = [float(point[1]) for point in dst]
        except (TypeError, ValueError, IndexError):
            ys = []
        contexts[index]["homography_world_y_min"] = min(ys) if ys else None
        contexts[index]["homography_world_y_max"] = max(ys) if ys else None
    for event in step_events:
        seq = int(event["seq_frame"])
        row = rows_by_seq.get(seq)
        cam = int(event.get("cam", row["cam"] if row else 0))
        context = contexts.get(cam)
        if row is None or context is None:
            continue
        side = str(event.get("foot", row["lower_foot"])).lower()
        ankle = (row[f"{side}_ankle_x"], row[f"{side}_ankle_y"])
        local = _runway_local(ankle, context["geometry"])
        # Use only plausible ankle touchdown anchors to establish the robust
        # per-camera ground band; bad foot points must never teach this model.
        if local is not None and -0.35 <= float(local[1]) <= 1.35:
            context["ground_values"].append(float(local[1]))

    for seq, per_side in foot_contacts_by_seq.items():
        row = rows_by_seq.get(seq)
        if row is None:
            continue
        context = contexts.get(int(row["cam"]))
        if context is None:
            continue
        for side, values in per_side.items():
            ankle = np.asarray([row[f"{side}_ankle_x"], row[f"{side}_ankle_y"]], dtype=float)
            for joint in ("heel", "big_toe"):
                candidate = values[joint]
                if candidate["conf"] < CONTACT_CONFIDENCE_THRESHOLD:
                    continue
                point = np.asarray([candidate["x"], candidate["y"]], dtype=float)
                if np.isfinite(point).all():
                    context["attachment_samples"][joint].append(float(np.linalg.norm(point - ankle)))

    for context in contexts.values():
        values = np.asarray(context.pop("ground_values"), dtype=float)
        if len(values):
            center = float(np.median(values))
            mad = float(np.median(np.abs(values - center)))
            context["ground_center"] = center
            # A generous 3-MAD band remains resistant to one incorrect foot
            # detection while accommodating ordinary lane and perspective drift.
            context["ground_tolerance"] = max(CONTACT_GROUND_BAND_MIN_TOLERANCE, 3.0 * mad)
        else:
            context["ground_center"] = None
            context["ground_tolerance"] = None
        thresholds = {}
        for joint, samples in context["attachment_samples"].items():
            p95 = float(np.percentile(samples, 95)) if samples else 0.0
            thresholds[joint] = max(12.0 if joint == "heel" else 18.0, p95 * 1.5)
        context["attachment_thresholds"] = thresholds
        context.pop("attachment_samples", None)
    return contexts


def _validate_foot_contact(candidate, joint, ankle_x, ankle_y, context):
    """Return validity flags and auditable rejection reasons for a foot point."""
    point = (candidate["x"], candidate["y"])
    reasons = []
    runway_valid = ground_band_valid = attachment_valid = True
    geometry = (context or {}).get("geometry")
    local = _runway_local(point, geometry)
    if local is not None:
        # The cone clicks define a nominal lane, but a camera can view a runner
        # a little above/below that strip.  Keep a calibration-tolerant margin;
        # the independently learned ground band remains the stricter guard for
        # a grossly elevated point such as the reported S13 heel.
        runway_valid = _within_runway_quad(local)
        if not runway_valid:
            reasons.append("outside_runway_quadrilateral")
        center, tolerance = (context or {}).get("ground_center"), (context or {}).get("ground_tolerance")
        if center is not None and tolerance is not None:
            ground_band_valid = abs(float(local[1]) - center) <= tolerance
            if not ground_band_valid:
                reasons.append("outside_camera_ground_band")

    distance = float(np.hypot(candidate["x"] - ankle_x, candidate["y"] - ankle_y))
    threshold = (context or {}).get("attachment_thresholds", {}).get(joint, 12.0)
    attachment_valid = distance <= threshold
    if not attachment_valid:
        reasons.append("foot_too_far_from_same_side_ankle")
    # A heel selected as a ground contact should not be conspicuously above
    # the ankle.  When it is, a valid toe or the ankle itself is safer.
    vertical_tolerance = max(5.0, threshold * 0.25)
    if candidate["y"] < ankle_y - vertical_tolerance:
        attachment_valid = False
        reasons.append("foot_above_ankle_ground_level")
    return {
        "valid": runway_valid and ground_band_valid and attachment_valid,
        "runway_valid": runway_valid,
        "ground_band_valid": ground_band_valid,
        "attachment_valid": attachment_valid,
        "reasons": reasons,
    }


def _validate_ankle_contact(ankle_x, ankle_y, context):
    """The final ankle fallback must still be on the camera's ground band."""
    point = (ankle_x, ankle_y)
    local = _runway_local(point, (context or {}).get("geometry"))
    reasons = []
    runway_valid = True
    ground_valid = True
    if local is not None:
        runway_valid = _within_runway_quad(local)
        if not runway_valid:
            reasons.append("ankle_outside_runway_quadrilateral")
        center, tolerance = (context or {}).get("ground_center"), (context or {}).get("ground_tolerance")
        ground_valid = center is None or tolerance is None or abs(float(local[1]) - center) <= tolerance
        if not ground_valid:
            reasons.append("ankle_outside_camera_ground_band")

    return runway_valid and ground_valid, reasons


def select_contact_point(foot, ankle_x, ankle_y, ankle_conf, foot_contacts, context=None):
    """Choose landing position without changing the ankle-derived event time.

    Priority is heel, then big toe, then ankle.  A point must have finite
    coordinates and WholeBody confidence >= 0.50 before it can replace the
    ankle.  The explicit reason is persisted in CSVs for inspection.
    """
    side = str(foot).lower()
    candidates = (foot_contacts or {}).get(side, {})
    validation = {}
    for joint in ("heel", "big_toe"):
        candidate = candidates.get(joint)
        if candidate is None:
            validation[joint] = {"valid": False, "reasons": ["point_missing"]}
            continue
        x, y, conf = candidate["x"], candidate["y"], candidate["conf"]
        if not np.isfinite([x, y, conf]).all() or conf < CONTACT_CONFIDENCE_THRESHOLD:
            validation[joint] = {"valid": False, "reasons": ["confidence_below_0_50"]}
            continue
        check = _validate_foot_contact(candidate, joint, ankle_x, ankle_y, context)
        validation[joint] = check
        if check["valid"]:
            return {
                "contact_joint": f"{side}_{joint}",
                "contact_x": float(x), "contact_y": float(y),
                "contact_conf": float(conf),
                "contact_selection_reason": f"{joint}_confidence_ge_{CONTACT_CONFIDENCE_THRESHOLD:.2f}",
                "heel_valid": bool(validation.get("heel", {}).get("valid", False)),
                "big_toe_valid": bool(validation.get("big_toe", {}).get("valid", False)),
                "runway_valid": bool(check["runway_valid"]),
                "attachment_valid": bool(check["attachment_valid"]),
                "ground_band_valid": bool(check["ground_band_valid"]),
                "contact_rejection_reason": "",
                "contact_valid": True,
            }
    rejected = ";".join(
        f"{joint}:{'|'.join(data.get('reasons', []))}"
        for joint, data in validation.items() if not data.get("valid"))
    ankle_valid, ankle_reasons = _validate_ankle_contact(ankle_x, ankle_y, context)
    if not ankle_valid:
        return {
            "contact_joint": f"{side}_invalid",
            "contact_x": float(ankle_x), "contact_y": float(ankle_y),
            "contact_conf": float(ankle_conf),
            "contact_selection_reason": "all_contact_candidates_rejected",
            "heel_valid": False, "big_toe_valid": False,
            "runway_valid": False, "attachment_valid": False, "ground_band_valid": False,
            "contact_rejection_reason": rejected + ";" + "|".join(ankle_reasons),
            "contact_valid": False,
        }
    return {
        "contact_joint": f"{side}_ankle",
        "contact_x": float(ankle_x), "contact_y": float(ankle_y),
        "contact_conf": float(ankle_conf),
        "contact_selection_reason": "heel_and_big_toe_rejected_or_unavailable__ankle_fallback",
        "heel_valid": bool(validation.get("heel", {}).get("valid", False)),
        "big_toe_valid": bool(validation.get("big_toe", {}).get("valid", False)),
        "runway_valid": True,
        "attachment_valid": True,
        "ground_band_valid": True,
        "contact_rejection_reason": rejected,
        "contact_valid": True,
    }


@dataclass(frozen=True)
class _PeakContext:
    """Per-call scalar context shared by the step-detection stages."""

    calibration: dict
    fps: float
    peak_distance: int
    min_step_frames: int
    min_touchdown_gap_frames: int
    raw_prominence: float


def _estimate_fps_from_rows(ankle_rows):
    """Estimate FPS from ankle_rows timestamps; falls back to 30.0."""
    if len(ankle_rows) >= 2:
        t0 = float(ankle_rows[0]['seq_time_s'])
        t1 = float(ankle_rows[-1]['seq_time_s'])
        if t1 > t0:
            return (len(ankle_rows) - 1) / (t1 - t0)
    return 30.0


def _lowpass_touchdown_signal(values, fps):
    """Low-pass Butterworth at 6 Hz: removes skeleton jitter while preserving
    step peaks (~2-4 Hz). Used only for peak detection; reported ankle
    coordinates always come from the original rows."""
    if len(values) < 13:
        return values
    cutoff_hz = 6.0
    nyq = fps / 2.0
    if cutoff_hz >= nyq:
        return values
    b, a = butter(4, cutoff_hz / nyq, btype='low')
    return filtfilt(b, a, values)


def _valid_touchdown_conf(conf, min_conf):
    try:
        value = float(conf)
    except (TypeError, ValueError):
        return False
    return np.isnan(value) or value >= min_conf


def _candidate_within_calibrated_range(candidate, calibration):
    if calibration.get("mode") != "homography":
        return True
    world_x = _project((candidate["ankle_x"], candidate["ankle_y"]), calibration)
    x_min = calibration.get("world_x_min")
    x_max = calibration.get("world_x_max")
    if x_min is None or x_max is None:
        return True
    margin_m = 0.5
    return float(x_min) - margin_m <= world_x <= float(x_max) + margin_m


def _candidate_from_peak(ankle_rows, calibration, peak_idx, peak_prominence, source):
    row = ankle_rows[int(peak_idx)]
    conf = row["lower_ankle_conf"]
    if not _valid_touchdown_conf(conf, 0.30):
        return None
    # Foot label: whichever ankle is lower at this frame (lower_foot is pre-computed).
    candidate = {
        "row_idx": int(peak_idx),
        "row": row,
        "foot": row["lower_foot"],
        "ankle_x": row["lower_ankle_x"],
        "ankle_y": row["lower_ankle_y"],
        "ankle_conf": conf,
        "prominence": float(peak_prominence),
        "source": source,
    }
    if _candidate_within_calibrated_range(candidate, calibration):
        return candidate
    return None


def _candidate_track_pos(candidate, calibration):
    return _project((candidate["ankle_x"], candidate["ankle_y"]), calibration)


def _candidate_score(candidate):
    return (candidate["prominence"], candidate["ankle_conf"], candidate["ankle_y"])


def _detect_smoothed_touchdown_candidates(ankle_rows, y, y_lookahead, prominence, ctx):
    """Smooth the combined lower-ankle-y signal, run find_peaks(), and turn the
    peaks that belong to this camera into touchdown candidates.

    A distance of fps/8 (~7 at 60fps) lets alternating-foot peaks spaced
    ~fps/cadence/2 frames apart both be detected, unlike min_step_frames which
    is calibrated for same-foot intervals and would suppress every other step.
    """
    y_extended = np.concatenate([y, y_lookahead]) if len(y_lookahead) else y
    y_smooth = _lowpass_touchdown_signal(y_extended, ctx.fps)
    lower_prominence = prominence
    if lower_prominence is None:
        q75, q25 = np.nanpercentile(y_smooth[:len(y)], [75, 25])
        lower_prominence = max((q75 - q25) * 0.20, 1.5)

    peaks, props = find_peaks(
        y_smooth,
        distance=ctx.peak_distance,
        prominence=lower_prominence,
    )
    prominences = props.get("prominences", np.zeros(len(peaks), dtype=float))
    # Peaks in the appended lookahead tail belong to the next camera -- they
    # exist only so find_peaks() has trailing signal to judge a boundary
    # peak, never to become candidates here (see detect_steps' docstring).
    own_mask = peaks < len(y)
    peaks = peaks[own_mask]
    prominences = prominences[own_mask]

    candidates = []
    for peak_idx, peak_prominence in zip(peaks, prominences):
        candidate = _candidate_from_peak(
            ankle_rows, ctx.calibration, peak_idx, peak_prominence, "smooth"
        )
        if candidate is not None:
            candidates.append(candidate)
    return candidates


def _suppress_close_touchdowns(candidates, min_touchdown_gap_frames):
    """Drop touchdowns closer than min_touchdown_gap_frames, keeping the
    higher-scoring one of each too-close pair."""
    filtered = []
    for candidate in candidates:
        if not filtered:
            filtered.append(candidate)
            continue
        previous = filtered[-1]
        frame_gap = int(candidate["row"]["seq_frame"]) - int(previous["row"]["seq_frame"])
        if frame_gap < min_touchdown_gap_frames:
            if _candidate_score(candidate) > _candidate_score(previous):
                filtered[-1] = candidate
        else:
            filtered.append(candidate)
    return filtered


def _large_step_rescue_threshold(candidates, calibration):
    if len(candidates) < 3:
        return None

    positions = [_candidate_track_pos(candidate, calibration) for candidate in candidates]
    step_lengths = [
        abs(positions[i] - positions[i - 1])
        for i in range(1, len(positions))
    ]
    typical_step = float(np.nanmedian(step_lengths)) if step_lengths else 0.0
    thresholds = []
    if typical_step > 1e-6:
        thresholds.append(typical_step * 1.6)

    # If calibration is available, also treat implausibly long human steps
    # as a signal that an intermediate touchdown may have been missed.
    large_step_m = 2.46
    if calibration.get("mode") == "homography":
        thresholds.append(large_step_m)
    else:
        meters_per_pixel = calibration.get("meters_per_pixel")
        if meters_per_pixel:
            thresholds.append(large_step_m / float(meters_per_pixel))

    return min(thresholds) if thresholds else None


def _rescue_position_is_between(prev_candidate, rescue_candidate, next_candidate, calibration):
    prev_pos = _candidate_track_pos(prev_candidate, calibration)
    next_pos = _candidate_track_pos(next_candidate, calibration)
    rescue_pos = _candidate_track_pos(rescue_candidate, calibration)
    span = abs(next_pos - prev_pos)
    if span <= 1e-6:
        return True
    min_margin = 0.20 if calibration.get("mode") == "homography" else 20.0
    margin = max(min_margin, span * 0.25)
    return min(prev_pos, next_pos) - margin <= rescue_pos <= max(prev_pos, next_pos) + margin


def _rescue_height_is_plausible(prev_candidate, rescue_candidate, next_candidate, raw_prominence):
    # A raw rescue peak should be near the landing height of the surrounding
    # contacts. Peaks much higher in the image are usually ankle jitter,
    # even if they are local maxima in the raw signal.
    surrounding_y = min(float(prev_candidate["ankle_y"]), float(next_candidate["ankle_y"]))
    return float(rescue_candidate["ankle_y"]) >= surrounding_y - raw_prominence


def _rescue_split_is_plausible(prev_candidate, rescue_candidate, next_candidate, calibration):
    prev_pos = _candidate_track_pos(prev_candidate, calibration)
    next_pos = _candidate_track_pos(next_candidate, calibration)
    rescue_pos = _candidate_track_pos(rescue_candidate, calibration)
    span = abs(next_pos - prev_pos)
    if span <= 1e-6:
        return True
    before = abs(rescue_pos - prev_pos)
    after = abs(next_pos - rescue_pos)
    return min(before, after) >= span * 0.25


def _rescue_raw_peaks_in_large_gaps(filtered_candidates, ankle_rows, y, ctx):
    """Rescue narrow raw peaks that the low-pass filter may suppress.

    This is intentionally conservative: raw peaks are only considered inside
    unusually large time gaps or unusually large track-position gaps between
    smooth detections, and still must pass confidence, prominence, timing,
    and track-position checks.
    """
    raw_peaks, raw_props = find_peaks(
        y,
        distance=ctx.peak_distance,
        prominence=ctx.raw_prominence,
    )
    raw_prominences = {
        int(peak): float(prom)
        for peak, prom in zip(raw_peaks, raw_props.get("prominences", []))
    }
    smooth_peak_indexes = {c["row_idx"] for c in filtered_candidates}
    rescue_gap_frames = max(
        ctx.min_step_frames + ctx.peak_distance,
        int(round(ctx.min_step_frames * 1.8)),
    )
    large_step_rescue_threshold = _large_step_rescue_threshold(
        filtered_candidates, ctx.calibration
    )

    rescued_candidates = []
    for prev_candidate, next_candidate in zip(filtered_candidates, filtered_candidates[1:]):
        rescued_candidates.append(prev_candidate)
        gap = int(next_candidate["row"]["seq_frame"]) - int(prev_candidate["row"]["seq_frame"])
        movement = abs(
            _candidate_track_pos(next_candidate, ctx.calibration)
            - _candidate_track_pos(prev_candidate, ctx.calibration)
        )
        large_step_gap = (
            large_step_rescue_threshold is not None
            and movement > large_step_rescue_threshold
        )
        if gap < rescue_gap_frames and not large_step_gap:
            continue

        prev_idx = prev_candidate["row_idx"]
        next_idx = next_candidate["row_idx"]
        middle_raw_candidates = []
        for peak_idx in raw_peaks:
            peak_idx = int(peak_idx)
            if peak_idx in smooth_peak_indexes:
                continue
            if not (prev_idx < peak_idx < next_idx):
                continue
            if peak_idx - prev_idx < ctx.min_touchdown_gap_frames:
                continue
            if next_idx - peak_idx < ctx.min_touchdown_gap_frames:
                continue

            candidate = _candidate_from_peak(
                ankle_rows,
                ctx.calibration,
                peak_idx,
                raw_prominences.get(peak_idx, 0.0),
                "raw_rescue",
            )
            if candidate is None:
                continue
            if not _valid_touchdown_conf(candidate["ankle_conf"], 0.50):
                continue
            if candidate["prominence"] < ctx.raw_prominence:
                continue
            if not _rescue_position_is_between(
                prev_candidate, candidate, next_candidate, ctx.calibration
            ):
                continue
            if not _rescue_height_is_plausible(
                prev_candidate, candidate, next_candidate, ctx.raw_prominence
            ):
                continue
            if not _rescue_split_is_plausible(
                prev_candidate, candidate, next_candidate, ctx.calibration
            ):
                continue
            middle_raw_candidates.append(candidate)

        if middle_raw_candidates:
            middle_raw_candidates.sort(key=_candidate_score, reverse=True)
            rescued_candidates.append(middle_raw_candidates[0])

    if filtered_candidates:
        rescued_candidates.append(filtered_candidates[-1])
    return sorted(rescued_candidates, key=lambda c: c["row_idx"])


def _min_valid_step_track_units(calibration):
    # Normal running step length is usually well above 0.6 m. Values below
    # this are more likely duplicate contacts from ankle jitter than true
    # alternating touchdowns. Keep this conservative for short runners or
    # slow jogs.
    min_step_length_m = 0.60
    if calibration.get("mode") == "homography":
        return min_step_length_m

    meters_per_pixel = calibration.get("meters_per_pixel")
    if meters_per_pixel:
        return min_step_length_m / float(meters_per_pixel)

    return None


def _dedupe_short_contacts(candidates, ctx):
    if len(candidates) < 2:
        return candidates

    positions = [_candidate_track_pos(candidate, ctx.calibration) for candidate in candidates]
    step_lengths = [
        abs(positions[i] - positions[i - 1])
        for i in range(1, len(positions))
    ]
    typical_step_px = float(np.nanmedian(step_lengths)) if step_lengths else 0.0
    absolute_short_step = _min_valid_step_track_units(ctx.calibration)
    if absolute_short_step is not None:
        short_step_px = max(absolute_short_step, typical_step_px * 0.35)
    else:
        short_step_px = max(20.0, typical_step_px * 0.35)
    short_gap_frames = max(ctx.min_touchdown_gap_frames, int(round(ctx.fps / 5.0)))

    deduped = []
    for candidate in candidates:
        if not deduped:
            deduped.append(candidate)
            continue

        previous = deduped[-1]
        gap = int(candidate["row"]["seq_frame"]) - int(previous["row"]["seq_frame"])
        movement = abs(
            _candidate_track_pos(candidate, ctx.calibration)
            - _candidate_track_pos(previous, ctx.calibration)
        )
        duplicate = (
            (movement < short_step_px) or
            (gap < short_gap_frames and movement < short_step_px)
        )
        if duplicate:
            if _candidate_score(candidate) > _candidate_score(previous):
                deduped[-1] = candidate
        else:
            deduped.append(candidate)
    return deduped


def _apply_alternating_foot_labels(candidates, ankle_rows, peak_distance):
    # 跑步必定左右交替落地。逐幀計算的 lower_foot 只在單一幀比較左右腳踝
    # y 座標，容易被雜訊誤判，因此只信任它來決定「第一步」（用峰值附近一
    # 個小視窗做多數決，降低錨點本身判斷錯誤的機率）。第二步以後一律直接
    # 取前一步的相反腳，不再重新讀取 lower_foot。落地時間點與
    # ankle_x/ankle_y（實際偵測到的踝關節位置）完全不變，只修正 foot 這個標籤欄位。
    if not candidates:
        return candidates

    anchor_window_radius = max(1, peak_distance // 3)
    anchor_row_idx = candidates[0]["row_idx"]
    lo = max(0, anchor_row_idx - anchor_window_radius)
    hi = min(len(ankle_rows) - 1, anchor_row_idx + anchor_window_radius)
    votes = [ankle_rows[i]["lower_foot"] for i in range(lo, hi + 1)]
    left_votes = votes.count("left")
    right_votes = votes.count("right")
    if left_votes > right_votes:
        anchor_foot = "left"
    elif right_votes > left_votes:
        anchor_foot = "right"
    else:
        anchor_foot = candidates[0]["foot"]  # tie: 保留原本單幀判斷值

    candidates[0]["foot"] = anchor_foot
    for i in range(1, len(candidates)):
        candidates[i]["foot"] = "left" if candidates[i - 1]["foot"] == "right" else "right"
    return candidates


def _build_step_events(candidates, calibration):
    """Project each labelled touchdown and emit the stable step-event dict."""
    events = []
    prev_proj = None
    for step_idx, candidate in enumerate(candidates, start=1):
        row = candidate["row"]
        point = (candidate["ankle_x"], candidate["ankle_y"])
        track_pos = _project(point, calibration)
        world_x = world_y = None
        if calibration.get("mode") == "homography":
            world_x, world_y = _transform_homography(point, calibration["homography"])
            step_len_px = None
            step_len_m = None if prev_proj is None else abs(track_pos - prev_proj)
        else:
            step_len_px = None if prev_proj is None else abs(track_pos - prev_proj)
            mpp = calibration["meters_per_pixel"]
            step_len_m = None if step_len_px is None or mpp is None else step_len_px * mpp
        prev_proj = track_pos

        events.append({
            "step_index": step_idx,
            "seq_frame": row["seq_frame"],
            "orig_frame": row["orig_frame"],
            "time_s": row["time_s"],
            "seq_time_s": row["seq_time_s"],
            "cam": row["cam"],
            "foot": candidate["foot"],
            "ankle_x": candidate["ankle_x"],
            "ankle_y": candidate["ankle_y"],
            "ankle_conf": candidate["ankle_conf"],
            "track_position_px": None if calibration.get("mode") == "homography" else track_pos,
            "world_x_m": world_x,
            "world_y_m": world_y,
            "step_length_px": step_len_px,
            "step_length_m": step_len_m,
        })

    return events


def detect_steps(ankle_rows, calibration, fps=None, min_step_frames=None, prominence=None,
                  lookahead_rows=None):
    """lookahead_rows: a few frames from the *next* camera, appended only so
    find_peaks() has enough trailing signal to confirm/reject a touchdown
    sitting right at this camera's tracked-window boundary (a peak with no
    frames after it in ankle_rows can't be told apart from a still-rising
    swing). These rows never become candidates themselves -- the next
    camera's own detect_steps() call is what actually detects them.
    """
    if not ankle_rows:
        return []

    fps = fps if fps is not None else _estimate_fps_from_rows(ankle_rows)
    fps = fps or 30.0
    if min_step_frames is None:
        # Minimum frames between consecutive touchdowns based on fps.
        # Assumes max cadence ~4.5 steps/s per foot (270 spm).
        min_step_frames = max(4, int(fps / 4.5))

    y = np.array([r["lower_ankle_y"] for r in ankle_rows], dtype=float)
    lookahead_rows = lookahead_rows or []
    y_lookahead = np.array([r["lower_ankle_y"] for r in lookahead_rows], dtype=float)
    raw_q75, raw_q25 = np.nanpercentile(y, [75, 25])
    ctx = _PeakContext(
        calibration=calibration,
        fps=fps,
        peak_distance=max(3, int(fps / 8.0)),
        min_step_frames=min_step_frames,
        min_touchdown_gap_frames=max(3, min_step_frames // 2),
        raw_prominence=max((raw_q75 - raw_q25) * 0.20, 1.5),
    )

    candidates = _detect_smoothed_touchdown_candidates(
        ankle_rows, y, y_lookahead, prominence, ctx
    )
    candidates = _suppress_close_touchdowns(candidates, ctx.min_touchdown_gap_frames)
    candidates = _rescue_raw_peaks_in_large_gaps(candidates, ankle_rows, y, ctx)
    candidates = _dedupe_short_contacts(candidates, ctx)
    candidates = _apply_alternating_foot_labels(candidates, ankle_rows, ctx.peak_distance)
    return _build_step_events(candidates, ctx.calibration)


def add_cadence(step_events):
    """Add instantaneous and summary cadence in steps per minute."""
    if not step_events:
        return None

    prev_time = None
    intervals = []
    for event in step_events:
        cadence = None
        current_time = float(event["time_s"])
        if prev_time is not None:
            dt = current_time - prev_time
            if dt > 0:
                cadence = 60.0 / dt
                intervals.append(dt)
        event["cadence_spm"] = cadence
        prev_time = current_time

    if len(step_events) >= 2:
        elapsed = float(step_events[-1]["time_s"]) - float(step_events[0]["time_s"])
        if elapsed > 0:
            summary = (len(step_events) - 1) / elapsed * 60.0
        else:
            summary = None
    else:
        summary = None

    for event in step_events:
        event["avg_cadence_spm"] = summary
    return summary


def add_global_cadence(step_events, ankle_rows):
    """Add one full-video average cadence in steps per minute."""
    if not step_events or not ankle_rows:
        return None

    rows_sorted = sorted(ankle_rows, key=lambda row: int(row["seq_frame"]))
    duration = float(rows_sorted[-1]["seq_time_s"]) - float(rows_sorted[0]["seq_time_s"])
    summary = (len(step_events) / duration * 60.0) if duration > 0 else None

    prev_time = None
    for event in sorted(step_events, key=lambda item: int(item["seq_frame"])):
        cadence = None
        current_time = float(event["seq_time_s"])
        if prev_time is not None:
            dt = current_time - prev_time
            if dt > 0:
                cadence = 60.0 / dt
        event["cadence_spm"] = cadence
        event["avg_cadence_spm"] = summary
        prev_time = current_time

    return summary


def _clamp(value, lower, upper):
    return max(lower, min(upper, value))


def _leg_vectors(right_leg, left_leg):
    return np.asarray([
        right_leg[1] - right_leg[0],
        right_leg[2] - right_leg[0],
        left_leg[1] - left_leg[0],
        left_leg[2] - left_leg[0],
    ], dtype=np.float64)


def _knee_angle(leg):
    v1 = leg[0] - leg[1]
    v2 = leg[2] - leg[1]
    denom = np.linalg.norm(v1) * np.linalg.norm(v2)
    if denom < 1e-8:
        return 0.0
    cos_a = np.dot(v1, v2) / denom
    return float(np.degrees(np.arccos(np.clip(cos_a, -1.0, 1.0))))


def _estimate_seq_fps(events):
    """Median sequential FPS implied by consecutive step-event timestamps."""
    samples = []
    sorted_events = sorted(events, key=lambda item: int(item["seq_frame"]))
    for a, b in zip(sorted_events, sorted_events[1:]):
        frame_delta = int(b["seq_frame"]) - int(a["seq_frame"])
        if frame_delta <= 0:
            continue
        for time_key in ("seq_time_s", "time_s"):
            if a.get(time_key) is None or b.get(time_key) is None:
                continue
            try:
                time_delta = float(b[time_key]) - float(a[time_key])
            except (TypeError, ValueError):
                continue
            if time_delta > 1e-6:
                samples.append(frame_delta / time_delta)
                break
    if not samples:
        return 60.0
    fps = float(np.median(samples))
    if not np.isfinite(fps) or fps <= 0:
        return 60.0
    return fps


def _median_smoothed_ankle_velocity(kp):
    """Per-frame ankle speed for each foot, median-smoothed over a 3-frame window."""
    frames = kp.shape[0]
    ankle_vel = {"right": np.zeros(frames), "left": np.zeros(frames)}
    for t in range(1, frames):
        ankle_vel["right"][t] = np.linalg.norm(kp[t, R_ANKLE] - kp[t - 1, R_ANKLE])
        ankle_vel["left"][t] = np.linalg.norm(kp[t, L_ANKLE] - kp[t - 1, L_ANKLE])
    for foot in ("right", "left"):
        padded = np.pad(ankle_vel[foot], (1, 1), mode="edge")
        ankle_vel[foot] = np.asarray(
            [np.median(padded[t:t + 3]) for t in range(frames)], dtype=np.float64
        )
    return ankle_vel


@dataclass(frozen=True)
class _LegSolverWeights:
    """Cost weights and margins for the anchor-DP leg-identity Viterbi solver."""

    vector_weight: float = 1.0
    coord_weight: float = 0.20
    switch_penalty: float = 8.0
    stance_penalty: float = 90.0
    anchor_penalty: float = 1000.0
    velocity_weight: float = 1.0
    y_weight: float = 0.25
    knee_angle_weight: float = 0.4
    velocity_margin: float = 3.0
    knee_angle_margin: float = 15.0
    early_switch_until: float = 0.65
    early_switch_weight: float = 50.0


class _LegIdentitySolver:
    """Per-segment Viterbi solver deciding, frame by frame between two touchdown
    anchors, whether the left/right leg labels are swapped (state 1) or not
    (state 0). Holds the shared 2D keypoints, smoothed ankle velocity, and
    sequential FPS so the cost functions do not thread them individually.
    """

    LEG_L = [L_HIP, L_KNEE, L_ANKLE]
    LEG_R = [R_HIP, R_KNEE, R_ANKLE]

    def __init__(self, kp, ankle_vel, seq_fps, weights=_LegSolverWeights()):
        self.kp = kp
        self.ankle_vel = ankle_vel
        self.seq_fps = seq_fps
        self.w = weights

    def _stance_extent(self, anchor_t, other_end_t, foot):
        # The stance influence range must not depend on the pre-DP left/right
        # labels, because those labels are exactly what DP is trying to resolve.
        # Use a fixed fraction of the adjacent touchdown gap, with FPS-scaled
        # min/max guards so the same seconds are covered at 30/60/120 fps.
        step = 1 if other_end_t > anchor_t else -1
        gap = abs(int(other_end_t) - int(anchor_t))
        if gap <= 1:
            return anchor_t

        if step > 0:
            raw_window = int(round(gap * 0.35))
            min_window = max(1, int(round(self.seq_fps * 0.04)))
            max_window = max(min_window, int(round(self.seq_fps * 0.12)))
        else:
            raw_window = int(round(gap * 0.20))
            min_window = max(1, int(round(self.seq_fps * 0.02)))
            max_window = max(min_window, int(round(self.seq_fps * 0.07)))

        window = _clamp(raw_window, min_window, max_window)
        window = min(window, gap - 1)
        return anchor_t + step * window

    def _legs_for_state(self, t, state):
        if state:
            return self.kp[t, self.LEG_L], self.kp[t, self.LEG_R]
        return self.kp[t, self.LEG_R], self.kp[t, self.LEG_L]

    def _transition_cost(self, prev_t, prev_state, t, state):
        prev_r, prev_l = self._legs_for_state(prev_t, prev_state)
        cur_r, cur_l = self._legs_for_state(t, state)
        vector_cost = np.linalg.norm(
            _leg_vectors(cur_r, cur_l) - _leg_vectors(prev_r, prev_l),
            axis=1,
        ).sum()
        coord_cost = (
            np.linalg.norm(cur_r - prev_r, axis=1).sum() +
            np.linalg.norm(cur_l - prev_l, axis=1).sum()
        )
        cost = self.w.vector_weight * vector_cost + self.w.coord_weight * coord_cost
        if state != prev_state:
            cost += self.w.switch_penalty
        return cost

    def _lower_foot_for_state(self, t, state):
        right_leg, left_leg = self._legs_for_state(t, state)
        return "right" if right_leg[2, 1] >= left_leg[2, 1] else "left"

    def _foot_mismatch_penalty(self, t, state, expected_foot, penalty):
        if self._lower_foot_for_state(t, state) == expected_foot:
            return 0.0
        right_leg, left_leg = self._legs_for_state(t, state)
        if expected_foot == "right":
            y_gap = max(0.0, float(left_leg[2, 1] - right_leg[2, 1]))
        else:
            y_gap = max(0.0, float(right_leg[2, 1] - left_leg[2, 1]))
        return penalty + y_gap

    def _stance_evidence_cost(self, t, state, expected_foot, penalty):
        right_leg, left_leg = self._legs_for_state(t, state)
        if expected_foot == "right":
            stance_leg, swing_leg = right_leg, left_leg
            stance_vel = self.ankle_vel["right"][t] if not state else self.ankle_vel["left"][t]
            swing_vel = self.ankle_vel["left"][t] if not state else self.ankle_vel["right"][t]
        else:
            stance_leg, swing_leg = left_leg, right_leg
            stance_vel = self.ankle_vel["left"][t] if not state else self.ankle_vel["right"][t]
            swing_vel = self.ankle_vel["right"][t] if not state else self.ankle_vel["left"][t]

        velocity_cost = max(0.0, self.w.velocity_margin - float(swing_vel - stance_vel))
        y_cost = max(0.0, float(swing_leg[2, 1] - stance_leg[2, 1]))
        angle_gap = _knee_angle(stance_leg) - _knee_angle(swing_leg)
        angle_cost = max(0.0, self.w.knee_angle_margin - angle_gap)
        return penalty + (
            self.w.velocity_weight * velocity_cost +
            self.w.y_weight * y_cost +
            self.w.knee_angle_weight * angle_cost
        )

    def _observation_cost(self, t, state, t_a, foot_a, t_b, foot_b, post_end, pre_start):
        if t == t_a:
            return self._foot_mismatch_penalty(t, state, foot_a, self.w.anchor_penalty)
        if t == t_b:
            return self._foot_mismatch_penalty(t, state, foot_b, self.w.anchor_penalty)

        near_start = t <= post_end
        near_end = t >= pre_start
        if near_start and near_end:
            expected = foot_a if (t - t_a) <= (t_b - t) else foot_b
            return self._stance_evidence_cost(t, state, expected, self.w.stance_penalty)
        if near_start:
            return self._stance_evidence_cost(t, state, foot_a, self.w.stance_penalty)
        if near_end:
            return self._stance_evidence_cost(t, state, foot_b, self.w.stance_penalty)
        return 0.0

    def _switch_timing_cost(self, t_a, t_b, t, prev_state, state):
        if state == prev_state:
            return 0.0
        span = max(1, t_b - t_a)
        progress = (t - t_a) / span
        if progress >= self.w.early_switch_until:
            return 0.0
        return (self.w.early_switch_until - progress) * self.w.early_switch_weight

    def solve_segment(self, t_a, foot_a, t_b, foot_b):
        post_end = self._stance_extent(t_a, t_b, foot_a)
        pre_start = self._stance_extent(t_b, t_a, foot_b)

        frames = list(range(t_a, t_b + 1))
        dp = np.full((len(frames), 2), np.inf, dtype=np.float64)
        parent = np.full((len(frames), 2), -1, dtype=np.int8)

        for state in (0, 1):
            dp[0, state] = self._observation_cost(
                t_a, state, t_a, foot_a, t_b, foot_b, post_end, pre_start
            )

        for idx in range(1, len(frames)):
            t = frames[idx]
            prev_t = frames[idx - 1]
            for state in (0, 1):
                obs = self._observation_cost(
                    t, state, t_a, foot_a, t_b, foot_b, post_end, pre_start
                )
                best_cost = np.inf
                best_prev = 0
                for prev_state in (0, 1):
                    cost = (
                        dp[idx - 1, prev_state] +
                        self._transition_cost(prev_t, prev_state, t, state) +
                        obs +
                        self._switch_timing_cost(t_a, t_b, t, prev_state, state)
                    )
                    if cost < best_cost:
                        best_cost = cost
                        best_prev = prev_state
                dp[idx, state] = best_cost
                parent[idx, state] = best_prev

        states = {}
        state = int(np.argmin(dp[-1]))
        for idx in range(len(frames) - 1, -1, -1):
            states[frames[idx]] = state
            state = int(parent[idx, state]) if idx > 0 else state

        return states


def _persist_corrected_reconstruction(recon, valid_frames, swapped, keypoints_npz_path):
    """Fill post-DP leg gaps, smooth/limit leg geometry, and overwrite the npz."""
    _post_dp_fill_leg_gaps(recon, swapped, keypoints_npz_path)
    _post_dp_smooth_and_limit_legs(recon)
    np.savez_compressed(
        keypoints_npz_path, reconstruction=recon, valid_frames=valid_frames
    )


def apply_anchor_leg_correction(keypoints_npz_path, step_events):
    """Refine 2D keypoint L/R leg identity using confirmed touchdown events.

    step_events (from detect_steps(), already guaranteed to alternate feet)
    are used as ground-truth anchors: at each touchdown's seq_frame, the
    stance (lower) ankle is known to be left or right. Between two
    consecutive anchors, leg identity is propagated frame-to-frame by
    least-movement continuity (only two legs to disambiguate, bounded by
    hard truth on both ends) -- this only refines segments that already
    have two anchors on both sides; frames before the first anchor or
    after the last keep whatever identity the pose-estimation stage
    already assigned (e.g. via cost-based correction).

    Overwrites keypoints_npz_path in place with the refined array and returns
    a boolean mask where True means that frame's left/right leg identity was
    swapped. If fewer than 2 step_events exist, returns None (not enough
    anchors to refine).
    """
    if len(step_events) < 2:
        return None

    data = np.load(keypoints_npz_path, allow_pickle=True)
    recon = data["reconstruction"]  # (M, T, J, C) -- C includes x, y, conf
    valid_frames = data["valid_frames"]

    kp = recon[0, :, :, :2].astype(np.float64)
    result = kp.copy()
    frame_count = kp.shape[0]

    solver = _LegIdentitySolver(
        kp,
        _median_smoothed_ankle_velocity(kp),
        _estimate_seq_fps(step_events),
    )
    leg_l, leg_r = _LegIdentitySolver.LEG_L, _LegIdentitySolver.LEG_R

    swapped = np.zeros(frame_count, dtype=bool)
    anchors = sorted(
        ((int(e["seq_frame"]), e["foot"]) for e in step_events),
        key=lambda a: a[0],
    )
    for (t_a, foot_a), (t_b, foot_b) in zip(anchors, anchors[1:]):
        if t_b <= t_a:
            continue
        states = solver.solve_segment(t_a, foot_a, t_b, foot_b)
        for t in range(t_a, t_b + 1):
            if states.get(t, 0):
                result[t, leg_r] = kp[t, leg_l]
                result[t, leg_l] = kp[t, leg_r]
                swapped[t] = True
            else:
                result[t, leg_r] = kp[t, leg_r]
                result[t, leg_l] = kp[t, leg_l]

    recon[0, :, :, :2] = result
    _persist_corrected_reconstruction(recon, valid_frames, swapped, keypoints_npz_path)
    return swapped


_FOOT_LEFT = [0, 1, 2]   # L_big_toe, L_small_toe, L_heel
_FOOT_RIGHT = [3, 4, 5]  # R_big_toe, R_small_toe, R_heel


def _swap_foot_leg_identity(keypoints, scores, swapped_mask):
    """L/R identity swap of WholeBody foot points on the masked frames, in place."""
    for t in range(min(keypoints.shape[1], len(swapped_mask))):
        if swapped_mask[t]:
            keypoints[:, t, _FOOT_LEFT + _FOOT_RIGHT] = keypoints[:, t, _FOOT_RIGHT + _FOOT_LEFT]
            scores[:, t, _FOOT_LEFT + _FOOT_RIGHT] = scores[:, t, _FOOT_RIGHT + _FOOT_LEFT]


def _reanchor_foot_to_body(keypoints, swapped_mask, raw_keypoints_npz_path, keypoints_npz_path):
    """Re-express each foot point as an offset from the raw ankle it was detected
    next to, then re-apply that offset to the final smoothed ankle. In place.

    Foot points are never smoothed, so after post-DP leg smoothing / bone-length
    fixing moves the body ankle a raw foot point can sit tens of pixels away --
    most visible right after a DP swap. Skipped when either keypoints file is
    missing.
    """
    if not os.path.exists(raw_keypoints_npz_path) or not os.path.exists(keypoints_npz_path):
        return

    raw_body = np.load(raw_keypoints_npz_path, allow_pickle=True)["reconstruction"][0]
    final_body = np.load(keypoints_npz_path, allow_pickle=True)["reconstruction"][0]
    frame_count = min(
        keypoints.shape[1], raw_body.shape[0], final_body.shape[0], len(swapped_mask)
    )
    for t in range(frame_count):
        if swapped_mask[t]:
            raw_left_ankle, raw_right_ankle = raw_body[t, R_ANKLE, :2], raw_body[t, L_ANKLE, :2]
        else:
            raw_left_ankle, raw_right_ankle = raw_body[t, L_ANKLE, :2], raw_body[t, R_ANKLE, :2]
        final_left_ankle = final_body[t, L_ANKLE, :2]
        final_right_ankle = final_body[t, R_ANKLE, :2]
        for foot_idx in _FOOT_LEFT:
            keypoints[:, t, foot_idx] = final_left_ankle + (keypoints[:, t, foot_idx] - raw_left_ankle)
        for foot_idx in _FOOT_RIGHT:
            keypoints[:, t, foot_idx] = final_right_ankle + (keypoints[:, t, foot_idx] - raw_right_ankle)


def apply_foot_leg_correction(
    foot_npz_path, raw_keypoints_npz_path, keypoints_npz_path, swapped_mask,
):
    """Correct WholeBody foot points to match the corrected body legs, in one
    read-modify-write of foot_keypoints.npz.

    Two stages: (1) apply the final raw-to-output L/R permutation to the foot
    points on the swapped frames, then (2) re-anchor them to the post-smoothing
    body ankles. ``swapped_mask`` must be the cumulative XOR mask covering both
    the preprocessing ``_correct_leg_swaps`` pass and ``apply_anchor_leg_correction``.

    keypoints order: L_big_toe, L_small_toe, L_heel, R_big_toe, R_small_toe, R_heel.

    No-ops (does not raise) if swapped_mask is None or foot_npz_path is missing;
    the re-anchor stage is additionally skipped when either keypoints file is
    missing.
    """
    if swapped_mask is None or not os.path.exists(foot_npz_path):
        return

    data = np.load(foot_npz_path, allow_pickle=True)
    keypoints = data["keypoints"].copy()  # (M, T, 6, 2)
    scores = data["scores"].copy()        # (M, T, 6)

    _swap_foot_leg_identity(keypoints, scores, swapped_mask)
    _reanchor_foot_to_body(
        keypoints, swapped_mask, raw_keypoints_npz_path, keypoints_npz_path
    )

    np.savez_compressed(
        foot_npz_path,
        keypoints=keypoints,
        scores=scores,
        valid_frames=data["valid_frames"],
        keypoint_names=data["keypoint_names"],
    )


def combine_leg_swap_masks(pre_dp_swapped_mask, anchor_dp_swapped_mask):
    """Return the final raw-to-output leg permutation using XOR parity.

    Body legs can be swapped once by ``_correct_leg_swaps`` during 2D
    preprocessing and again by ``apply_anchor_leg_correction``.  Foot points
    start in raw WholeBody order, so they must receive the parity of both
    operations rather than only the anchor-DP mask.
    """
    if pre_dp_swapped_mask is None and anchor_dp_swapped_mask is None:
        return None
    if pre_dp_swapped_mask is None:
        return np.asarray(anchor_dp_swapped_mask, dtype=bool).copy()
    if anchor_dp_swapped_mask is None:
        return np.asarray(pre_dp_swapped_mask, dtype=bool).copy()

    pre = np.asarray(pre_dp_swapped_mask, dtype=bool).reshape(-1)
    anchor = np.asarray(anchor_dp_swapped_mask, dtype=bool).reshape(-1)
    total = max(len(pre), len(anchor))
    pre_aligned = np.zeros(total, dtype=bool)
    anchor_aligned = np.zeros(total, dtype=bool)
    pre_aligned[:len(pre)] = pre
    anchor_aligned[:len(anchor)] = anchor
    return np.logical_xor(pre_aligned, anchor_aligned)


def update_leg_swap_metadata(keypoints_npz_path, pre_dp_swapped_mask,
                             anchor_dp_swapped_mask):
    """Persist pre/anchor/final masks and return the final XOR mask."""
    final_mask = combine_leg_swap_masks(
        pre_dp_swapped_mask, anchor_dp_swapped_mask)
    if final_mask is None:
        return None

    mask_path = Path(keypoints_npz_path).parent / "post_dp_ankle_fill_mask.npz"
    values = {}
    if mask_path.exists():
        with np.load(mask_path, allow_pickle=True) as data:
            values = {name: data[name] for name in data.files}

    pre = np.asarray(pre_dp_swapped_mask, dtype=bool).reshape(-1)
    anchor = np.asarray(anchor_dp_swapped_mask, dtype=bool).reshape(-1)
    values.update({
        "pre_dp_leg_swapped": pre,
        "anchor_dp_leg_swapped": anchor,
        "final_leg_swapped": final_mask,
        # Backward-compatible key consumed by diagnostic sheet tooling.  It now
        # means the final raw-to-output identity permutation.
        "dp_leg_swapped": final_mask,
    })
    np.savez_compressed(mask_path, **values)
    return final_mask


def _long_jump_impact_position(rows, peak_index, foot):
    """Estimate horizontal impact position while retaining the observed impact height.

    At a sand landing the ankle heatmap often collapses exactly at maximum
    compression.  The raw peak still gives the most useful contact-time and
    vertical coordinate; its horizontal coordinate is interpolated from the
    nearest reliable same-side ankle observations when possible.
    """
    peak = rows[peak_index]
    prefix = "right" if foot == "right" else "left"
    before = after = None
    for index in range(peak_index - 1, -1, -1):
        row = rows[index]
        if float(row[f"{prefix}_ankle_conf"]) >= LONG_JUMP_NEIGHBOR_CONFIDENCE:
            before = (index, row)
            break
    for index in range(peak_index + 1, len(rows)):
        row = rows[index]
        if float(row[f"{prefix}_ankle_conf"]) >= LONG_JUMP_NEIGHBOR_CONFIDENCE:
            after = (index, row)
            break
    raw_x = float(peak[f"{prefix}_ankle_x"])
    raw_y = float(peak[f"{prefix}_ankle_y"])
    if before is None or after is None:
        return raw_x, raw_y, "low_confidence_impact_peak"
    before_index, before_row = before
    after_index, after_row = after
    if after_index - before_index > 18:
        return raw_x, raw_y, "low_confidence_impact_peak"
    ratio = (peak_index - before_index) / (after_index - before_index)
    estimated_x = float(before_row[f"{prefix}_ankle_x"]) + ratio * (
        float(after_row[f"{prefix}_ankle_x"]) - float(before_row[f"{prefix}_ankle_x"]))
    return estimated_x, raw_y, "trajectory_estimated"


def _find_terminal_long_jump_flight(rows, events, fps):
    """Return one confirmed terminal-camera airborne interval, if present.

    The normal step detector deliberately looks for local *downward* ankle
    peaks.  During a long jump, the descending foot can create the same peak
    while it is still in the air.  This helper instead requires the complete
    pattern ``ground -> sustained rise -> apex -> sustained return to ground``.
    Therefore events between takeoff and the first ground return are not steps
    and must be removed rather than moved sideways by homography correction.
    """
    if not rows or not events:
        return None

    min_airborne = max(
        int(round(float(fps) * LONG_JUMP_AIRBORNE_MIN_SECONDS)),
        int(round(float(fps) * LONG_JUMP_MIN_FLIGHT_SECONDS)),
    )
    row_index = {int(row["seq_frame"]): index for index, row in enumerate(rows)}
    event_indices = [
        (event, row_index.get(int(event["seq_frame"])))
        for event in events
    ]
    event_indices = [(event, index) for event, index in event_indices if index is not None]
    if not event_indices:
        return None

    best = None
    for event_pos, (previous, previous_index) in enumerate(event_indices):
        # A robust local ground height comes from the last few accepted running
        # contacts, not a single potentially noisy ankle sample.
        history = event_indices[max(0, event_pos - 2):event_pos + 1]
        ground_y = float(np.median([
            float(rows[index]["lower_ankle_y"]) for _, index in history
        ]))
        start_limit = min(len(rows), previous_index + int(round(float(fps) * 2.5)))
        if start_limit - previous_index <= min_airborne:
            continue

        rise_index = None
        for index in range(previous_index + 1, start_limit - 1):
            # Two consecutive points avoid interpreting one HRNet jitter frame
            # as a takeoff.
            if (float(rows[index]["lower_ankle_y"]) <= ground_y - LONG_JUMP_AIRBORNE_RISE_PX
                    and float(rows[index + 1]["lower_ankle_y"]) <= ground_y - LONG_JUMP_AIRBORNE_RISE_PX):
                rise_index = index
                break
        if rise_index is None:
            continue

        # Find the *first* return to the local ground height.  Do not search
        # for an apex across the entire remaining camera window: a normal
        # preceding stride can rise and return before the real takeoff, and
        # joining those arcs would delete that valid touchdown.
        return_index = None
        for index in range(rise_index + 1, start_limit - 1):
            if (float(rows[index]["lower_ankle_y"]) >= ground_y - LONG_JUMP_GROUND_RETURN_TOLERANCE_PX
                    and float(rows[index + 1]["lower_ankle_y"]) >= ground_y - LONG_JUMP_GROUND_RETURN_TOLERANCE_PX):
                return_index = index
                break
        if return_index is None:
            continue

        # A normal running swing returns to ground too quickly to be a long
        # jump.  Let the next accepted contact start a fresh flight search.
        if return_index - rise_index < min_airborne:
            continue

        # The apex belongs strictly to this one airborne arc.
        y_window = [float(rows[index]["lower_ankle_y"])
                    for index in range(rise_index, return_index + 1)]
        apex_index = rise_index + int(np.argmin(y_window))
        if apex_index <= rise_index:
            continue

        excursion = ground_y - float(rows[apex_index]["lower_ankle_y"])
        if excursion < LONG_JUMP_MIN_VERTICAL_EXCURSION_PX:
            continue
        score = excursion + (return_index - rise_index) * 0.5
        candidate = {
            "previous": previous,
            "previous_index": previous_index,
            "flight_start_index": rise_index,
            "apex_index": apex_index,
            "return_index": return_index,
            "ground_y": ground_y,
            "score": score,
        }
        if best is None or candidate["score"] > best["score"]:
            best = candidate
    return best


def _long_jump_lowest_impact_index(rows, ground_return_index, fps):
    """Return the first post-return compression low point of a sand landing.

    The first frame that re-enters the ground band proves touchdown but is
    commonly early: the ankle continues downward while the athlete compresses
    into the sand.  In image coordinates that compression is increasing y.
    Keep following it briefly, stopping at the first clear reversal so recovery
    motion cannot move the reported landing later.
    """
    window_end = min(len(rows), ground_return_index + max(4, int(round(float(fps) * 0.40))))
    best_index = ground_return_index
    best_y = float(rows[best_index]["lower_ankle_y"])
    rising_after_best = 0
    for index in range(ground_return_index + 1, window_end):
        value = float(rows[index]["lower_ankle_y"])
        if value >= best_y:
            best_index, best_y = index, value
            rising_after_best = 0
            continue
        if best_index > ground_return_index and value < best_y - 1.0:
            rising_after_best += 1
            if rising_after_best >= 2:
                break
    return best_index


def _final_landing_event(rows, impact_index, flight_start_frame, landing_score, selection_reason):
    """Build the shared 'final_landing' step-event record for a long-jump landing.

    The horizontal contact position is interpolated from the nearest reliable
    same-side ankle samples; heel/toe are never used for a sand impact.
    """
    peak = rows[impact_index]
    foot = str(peak["lower_foot"])
    contact_x, contact_y, position_source = _long_jump_impact_position(
        rows, impact_index, foot
    )
    return {
        "seq_frame": int(peak["seq_frame"]),
        "orig_frame": int(peak["orig_frame"]),
        "time_s": float(peak["time_s"]),
        "seq_time_s": float(peak["seq_time_s"]),
        "cam": int(peak["cam"]),
        "foot": foot,
        "event_type": "final_landing",
        "flight_start_frame": flight_start_frame,
        "landing_position_source": position_source,
        "landing_score": landing_score,
        "ankle_x": float(peak["lower_ankle_x"]),
        "ankle_y": float(peak["lower_ankle_y"]),
        "ankle_conf": float(peak["lower_ankle_conf"]),
        "contact_joint": f"{foot}_ankle_estimated",
        "contact_x": contact_x,
        "contact_y": contact_y,
        "contact_conf": float(peak["lower_ankle_conf"]),
        "contact_selection_reason": selection_reason,
        "heel_valid": False,
        "big_toe_valid": False,
        "runway_valid": True,
        "attachment_valid": True,
        "ground_band_valid": True,
        "contact_rejection_reason": "",
        "contact_valid": True,
    }


def _detect_long_jump_final_landing(ankle_rows, accepted_events, fps):
    """Find a low-confidence sand impact between two otherwise valid contacts.

    This is deliberately restricted to the final camera.  It detects the
    long-jump pattern ``ground -> rising ankle -> descending ankle -> impact``
    and replaces a delayed post-impact regular step with the first impact peak.
    No manually clicked takeoff or sand zone is required.
    """
    if not ankle_rows or not accepted_events:
        return None
    terminal_cam = max(int(row["cam"]) for row in ankle_rows)
    rows = [row for row in ankle_rows if int(row["cam"]) == terminal_cam]
    events = sorted((event for event in accepted_events if int(event["cam"]) == terminal_cam),
                    key=lambda event: int(event["seq_frame"]))
    # One confirmed final-camera running contact is enough to establish a
    # flight baseline; do not require a false post-takeoff peak to exist.
    if len(rows) < 8 or len(events) < 1:
        return None

    # Prefer a complete flight state over the older "large gap between two
    # detected peaks" heuristic.  The latter can retain a false regular peak
    # in mid-air; this path explicitly discards all such peaks.
    flight = _find_terminal_long_jump_flight(rows, events, fps)
    if flight is not None:
        impact_index = _long_jump_lowest_impact_index(
            rows, flight["return_index"], fps)
        return {
            **_final_landing_event(
                rows,
                impact_index,
                flight_start_frame=int(rows[flight["flight_start_index"]]["seq_frame"]),
                landing_score=float(flight["score"]),
                selection_reason="long_jump_confirmed_airborne_return",
            ),
            # Keep all ordinary candidates only up to the last confirmed
            # pre-takeoff contact.  Mid-air peaks are explicitly discarded.
            "_keep_through_seq": int(flight["previous"]["seq_frame"]),
        }
    row_index = {int(row["seq_frame"]): index for index, row in enumerate(rows)}
    min_gap = max(6, int(round(float(fps) * LONG_JUMP_MIN_EVENT_GAP_SECONDS)))
    min_flight = max(4, int(round(float(fps) * LONG_JUMP_MIN_FLIGHT_SECONDS)))
    best = None

    for previous, following in zip(events, events[1:]):
        previous_index = row_index.get(int(previous["seq_frame"]))
        following_index = row_index.get(int(following["seq_frame"]))
        if previous_index is None or following_index is None:
            continue
        if following_index - previous_index < min_gap:
            continue
        # Ignore the leading endpoint: `previous` is a genuine prior contact,
        # so its own peak height must stay excluded when measuring vertical
        # excursion. No trailing buffer: this function only ever runs on the
        # terminal camera, where no legitimate step can follow an
        # already-confirmed running step, so `following` (even if the
        # standard detector mistook the impact itself for a regular step)
        # can never be a real subsequent contact worth protecting against —
        # trimming frames near it only risks cutting off the true impact peak.
        inner_start, inner_end = previous_index + 3, following_index
        if inner_end <= inner_start:
            continue
        # Takeoff = the highest point of the flight arc (min y) anywhere in
        # this window; searched before impact_index below since it no longer
        # depends on it.
        window_rows = rows[inner_start:inner_end + 1]
        takeoff_index = inner_start + int(np.argmin(
            [float(row["lower_ankle_y"]) for row in window_rows]
        ))

        # Preferred candidate: the first sustained confidence collapse after
        # takeoff (the true touchdown instant, per the module docstring's
        # "confidence collapse" signature). Falls back to the deepest-y frame
        # only if the trial never shows a real collapse (clean tracking
        # throughout), so landings are still detected either way.
        impact_index = None
        collapse_run = 0
        for idx in range(takeoff_index, inner_end + 1):
            if float(rows[idx]["lower_ankle_conf"]) < LONG_JUMP_IMPACT_CONFIDENCE_THRESHOLD:
                collapse_run += 1
                if collapse_run >= LONG_JUMP_IMPACT_MIN_RUN:
                    impact_index = idx - collapse_run + 1
                    break
            else:
                collapse_run = 0

        if impact_index is not None:
            peak_index = impact_index
        else:
            y_values = np.asarray([float(row["lower_ankle_y"]) for row in window_rows], dtype=float)
            peak_index = inner_start + int(np.argmax(y_values))
        peak = rows[peak_index]
        excursion = float(peak["lower_ankle_y"]) - float(rows[takeoff_index]["lower_ankle_y"])
        # The peak must follow a genuine airborne dip and return to at least the
        # preceding contact height.  This excludes ordinary small gait jitter.
        if peak_index - takeoff_index < min_flight:
            continue
        if excursion < LONG_JUMP_MIN_VERTICAL_EXCURSION_PX:
            continue
        if float(peak["lower_ankle_y"]) < float(previous["ankle_y"]) - 5.0:
            continue
        score = excursion + (following_index - previous_index) * 0.25
        candidate = {
            "peak_index": peak_index,
            "takeoff_index": takeoff_index,
            "following": following,
            "score": score,
        }
        if best is None or candidate["score"] > best["score"]:
            best = candidate

    if best is None:
        return None
    return {
        **_final_landing_event(
            rows,
            best["peak_index"],
            flight_start_frame=int(rows[best["takeoff_index"]]["seq_frame"]),
            landing_score=float(best["score"]),
            selection_reason="long_jump_low_confidence_impact_peak",
        ),
        "_replace_after_seq": int(best["following"]["seq_frame"]),
    }


def _events_in_seq_order(events):
    return sorted(events, key=lambda item: int(item["seq_frame"]))


def _homography_cameras(calibrations):
    """Yield (cam_idx, calibration) for homography-calibrated cameras only."""
    for cam_idx, calibration in calibrations.items():
        if calibration and calibration.get("mode") == "homography":
            yield cam_idx, calibration


def _project_contacts_and_step_lengths(events, calibrations, contexts):
    """Pass 1: project every contact point, fill world/pixel coordinates and
    per-camera + cross-camera step lengths, and stash the raw homography
    world coordinates the later passes need."""
    previous_by_camera = {}
    previous_global_track_pos_m = None
    for event in _events_in_seq_order(events):
        cam_idx = int(event["cam"])
        calibration = calibrations.get(cam_idx)
        point = (float(event["contact_x"]), float(event["contact_y"]))
        track_pos = _project(point, calibration) if calibration else None
        previous = previous_by_camera.get(cam_idx)
        event["track_position_px"] = None if calibration and calibration.get("mode") == "homography" else track_pos
        event["world_x_m"] = event["world_y_m"] = None
        event["step_length_px"] = event["step_length_m"] = None
        if calibration and calibration.get("mode") == "homography":
            world_x, world_y = _transform_homography(point, calibration["homography"])
            # Keep the raw projected coordinates even when the lateral value is
            # rejected.  The along-runway X is still useful for step length;
            # a later pass replaces only the unreliable cross-track Y.
            event["_homography_raw_world_x"] = world_x
            event["_homography_raw_world_y"] = world_y
            event["homography_y_interpolated"] = False
            # The learned band comes from regular running-gait steps, which
            # sit close to the lane centerline; a long-jump landing legitimately
            # lands off that centerline, so don't hold it to the same band.
            is_landing = str(event.get("event_type", "")) == "final_landing"
            lateral_ok, _ = _validate_homography_lateral(point, contexts.get(cam_idx))
            # Only set for homography-mode events, so the overlay can tell
            # "line/pixel mode, world coords never applicable" (key absent)
            # apart from "homography mode, this specific point's world
            # coordinate was untrustworthy" (explicit False) -- world_x_m
            # being None alone can't carry that distinction. Must match the
            # same is_landing exemption as the data below, or the overlay
            # would mute a landing point whose world coords it still shows.
            event["homography_lateral_valid"] = lateral_ok or is_landing
            if lateral_ok or is_landing:
                event["world_x_m"], event["world_y_m"] = world_x, world_y
                event["step_length_m"] = None if previous is None else abs(track_pos - previous)
        elif previous is not None:
            event["step_length_px"] = abs(track_pos - previous)
            mpp = calibration.get("meters_per_pixel") if calibration else None
            event["step_length_m"] = None if mpp is None else event["step_length_px"] * mpp

        # Cross-camera bridge: each camera has its own local origin.  Convert
        # either a line projection or a Homography local X to the shared whole
        # runway coordinate before measuring the first step after a cut.
        track_pos_m = None
        if calibration and calibration.get("mode") == "homography" and event.get("world_x_m") is not None:
            track_pos_m = (
                calibration.get("camera_offset_m", 0.0)
                + float(event["world_x_m"])
                - float(calibration.get("world_x_min", 0.0))
            )
        elif calibration and calibration.get("mode") == "line" and track_pos is not None:
            mpp = calibration.get("meters_per_pixel")
            if mpp is not None:
                track_pos_m = calibration.get("camera_offset_m", 0.0) + track_pos * mpp
        if track_pos_m is not None:
            if event["step_length_m"] is None and previous_global_track_pos_m is not None:
                event["step_length_m"] = abs(track_pos_m - previous_global_track_pos_m)
            previous_global_track_pos_m = track_pos_m

        if track_pos is not None:
            previous_by_camera[cam_idx] = track_pos


def _reject_homography_lateral_temporal_jumps(events, calibrations):
    """Pass 2: a point can be inside the physical strip yet still be a one-frame
    pose jump. Compare only an interior event with both neighbouring valid
    events from the same camera; end points are deliberately left alone because
    they have no two-sided temporal evidence."""
    for cam_idx, _calibration in _homography_cameras(calibrations):
        camera_events = [
            event for event in _events_in_seq_order(events)
            if int(event.get("cam", -1)) == int(cam_idx)
            and event.get("world_y_m") is not None
            and str(event.get("event_type", "")) != "final_landing"
        ]
        # Snapshot the original world_y values before the loop mutates any of
        # them -- reading camera_events[...]["world_y_m"] live would crash on
        # two adjacent rejections (the second one's "previous" neighbour was
        # just nulled out by the first).
        original_world_y = [float(event["world_y_m"]) for event in camera_events]
        for index in range(1, len(camera_events) - 1):
            previous = original_world_y[index - 1]
            current = original_world_y[index]
            following = original_world_y[index + 1]
            expected = float(np.median([previous, following]))
            if abs(current - expected) <= HOMOGRAPHY_TEMPORAL_LATERAL_JUMP_M:
                continue
            event = camera_events[index]
            event["homography_lateral_valid"] = False
            event["world_x_m"] = event["world_y_m"] = None
            event["step_length_m"] = None
            prior_reason = str(event.get("contact_rejection_reason") or "")
            reason = "homography_lateral_temporal_jump"
            event["contact_rejection_reason"] = f"{prior_reason};{reason}".strip(";")


def _interpolate_rejected_homography_world_y(events, calibrations):
    """Pass 3: a rejected cross-track coordinate does not mean its gait event
    vanished. Preserve that event's raw forward X and timestamp, but estimate
    only Y from neighbouring trustworthy contacts. This prevents a pose heatmap
    jump from becoming either a false map point or a missing step."""
    for cam_idx, _calibration in _homography_cameras(calibrations):
        camera_events = [
            event for event in _events_in_seq_order(events)
            if int(event.get("cam", -1)) == int(cam_idx)
            and str(event.get("event_type", "")) != "final_landing"
        ]
        valid_indices = [
            index for index, event in enumerate(camera_events)
            if event.get("world_y_m") is not None
        ]
        for index, event in enumerate(camera_events):
            if event.get("world_y_m") is not None:
                continue
            raw_x = event.get("_homography_raw_world_x")
            if raw_x is None:
                continue
            before = [valid for valid in valid_indices if valid < index]
            after = [valid for valid in valid_indices if valid > index]
            prev_event = camera_events[before[-1]] if before else None
            next_event = camera_events[after[0]] if after else None
            if prev_event is not None and next_event is not None:
                prev_x, prev_y = float(prev_event["world_x_m"]), float(prev_event["world_y_m"])
                next_x, next_y = float(next_event["world_x_m"]), float(next_event["world_y_m"])
                span_x = next_x - prev_x
                ratio = (float(raw_x) - prev_x) / span_x if abs(span_x) > 1e-6 else 0.5
                estimated_y = prev_y + ratio * (next_y - prev_y)
            elif prev_event is not None:
                estimated_y = float(prev_event["world_y_m"])
            elif next_event is not None:
                estimated_y = float(next_event["world_y_m"])
            else:
                continue
            event["world_x_m"] = float(raw_x)
            event["world_y_m"] = float(estimated_y)
            event["homography_lateral_valid"] = True
            event["homography_y_interpolated"] = True
            prior_reason = str(event.get("contact_rejection_reason") or "")
            reason = "homography_y_interpolated"
            event["contact_rejection_reason"] = f"{prior_reason};{reason}".strip(";")


def _reject_homography_implausible_velocity(events, calibrations):
    """Pass 4 (velocity continuity): a contact point can pass the physical
    runway-bound check (layer 1, in _validate_homography_lateral()) yet still
    be a misdetection if it implies an impossible sprint speed to/from its
    neighbour -- e.g. the same distance jump happening in a much shorter time
    than a real stride takes. Checked only within a single camera's own clip:
    time_s resets at each camera cut, so a cross-camera pair's elapsed time
    isn't directly comparable, and a step spanning a camera cut is deliberately
    left unchecked by this layer."""
    for cam_idx, _calibration in _homography_cameras(calibrations):
        camera_events = [
            event for event in _events_in_seq_order(events)
            if int(event.get("cam", -1)) == int(cam_idx)
            and event.get("world_x_m") is not None
            and str(event.get("event_type", "")) != "final_landing"
        ]
        if len(camera_events) < 2:
            continue
        speeds = []
        for prev_event, cur_event in zip(camera_events, camera_events[1:]):
            dt = float(cur_event["time_s"]) - float(prev_event["time_s"])
            dx = float(cur_event["world_x_m"]) - float(prev_event["world_x_m"])
            speeds.append(abs(dx / dt) if dt > 0 else None)
        valid_speeds = [speed for speed in speeds if speed is not None]
        if not valid_speeds:
            continue
        median_speed = float(np.median(valid_speeds))
        for index in range(1, len(camera_events)):
            speed = speeds[index - 1]
            if speed is None:
                continue
            plausible = (
                speed <= HOMOGRAPHY_VELOCITY_ABS_CEILING_MPS
                and abs(speed - median_speed) <= HOMOGRAPHY_VELOCITY_RELATIVE_MULTIPLIER * median_speed
            )
            if plausible:
                continue
            event = camera_events[index]
            event["world_x_m"] = event["world_y_m"] = None
            event["step_length_m"] = None
            event["homography_lateral_valid"] = False
            prior_reason = str(event.get("contact_rejection_reason") or "")
            reason = "homography_velocity_implausible"
            event["contact_rejection_reason"] = f"{prior_reason};{reason}".strip(";")


def _recompute_global_homography_step_lengths(events, calibrations):
    """Pass 5: recalculate homography step lengths after any geometric/temporal
    rejection so no displayed distance is based on a hidden anchor."""
    previous_global_world_x = None
    for event in _events_in_seq_order(events):
        calibration = calibrations.get(int(event.get("cam", 0)))
        if not calibration or calibration.get("mode") != "homography":
            continue
        event["step_length_m"] = None
        if event.get("world_x_m") is None:
            continue
        global_world_x = (
            float(calibration.get("camera_offset_m", 0.0))
            + float(event["world_x_m"])
            - float(calibration.get("world_x_min", 0.0))
        )
        if previous_global_world_x is not None:
            event["step_length_m"] = abs(global_world_x - previous_global_world_x)
        previous_global_world_x = global_world_x


def _strip_internal_homography_keys(events):
    """Pass 6: internal values are used only while reconstructing this event
    list and must not leak into the stable CSV schema."""
    for event in events:
        event.pop("_homography_raw_world_x", None)
        event.pop("_homography_raw_world_y", None)


def _recompute_contact_event_metrics(events, calibrations, contexts=None):
    """Recompute distances after special landing replacement changes event order.

    contexts (from _contact_validation_contexts()) supplies each homography
    camera's learned plausible world_y band. A point outside it gets its
    world_x_m/world_y_m/step_length_m left as None rather than displaying an
    implausible position -- this only affects display/distance for that one
    event, not whether it stayed in `events` (which _detect_long_jump_final_
    landing() already used purely by frame position, upstream of this call).
    """
    contexts = contexts or {}
    _project_contacts_and_step_lengths(events, calibrations, contexts)
    _reject_homography_lateral_temporal_jumps(events, calibrations)
    _interpolate_rejected_homography_world_y(events, calibrations)
    _reject_homography_implausible_velocity(events, calibrations)
    _recompute_global_homography_step_lengths(events, calibrations)
    _strip_internal_homography_keys(events)


def _video_fps(video_path):
    """FPS of a video file, or 60.0 when it is missing or unreadable."""
    cap = cv2.VideoCapture(video_path) if video_path else None
    fps = cap.get(cv2.CAP_PROP_FPS) if cap and cap.isOpened() else 60.0
    if cap:
        cap.release()
    return fps or 60.0


def _first_camera_video_fps(cameras):
    """FPS of the first camera's video, or 60.0 when it cannot be read."""
    return _video_fps(cameras[0].get("video_path"))


def _normalize_line(line):
    return [(float(x), float(y)) for x, y in line] if line else line


def _build_sequential_calibrations(cameras, config, meters_per_pixel):
    """One calibration per camera, each carrying its cumulative along-runway
    offset.

    Cameras are laid out sequentially along the runway, but both line
    calibration and six-point Homography start their local X at zero. Stacking
    their physical spans into one global track coordinate lets a step that
    crosses a camera cut (e.g. S6 -> S7) have a real distance.
    """
    calibrations = {}
    cumulative_offset_m = 0.0
    for cam_idx, cam in enumerate(cameras):
        distance_m = cam.get("distance_m") or config.get("distance_m")
        calibration = _make_calibration(
            cam,
            config,
            meters_per_pixel,
            _normalize_line(cam.get("start_line")),
            _normalize_line(cam.get("end_line")),
            distance_m,
        )
        calibration["camera_offset_m"] = cumulative_offset_m
        if calibration.get("mode") == "homography":
            camera_span_m = (
                float(calibration.get("world_x_max", 0.0))
                - float(calibration.get("world_x_min", 0.0))
            )
        else:
            camera_span_m = float(distance_m) if distance_m is not None else 0.0
        cumulative_offset_m += max(0.0, camera_span_m)
        calibrations[cam_idx] = calibration
    return calibrations


def _ankle_for_foot(row, foot):
    if foot == "right":
        return row["right_ankle_x"], row["right_ankle_y"], row["right_ankle_conf"]
    if foot == "left":
        return row["left_ankle_x"], row["left_ankle_y"], row["left_ankle_conf"]
    return row["lower_ankle_x"], row["lower_ankle_y"], row["lower_ankle_conf"]


@dataclass(frozen=True)
class _RefreshContext:
    """Shared inputs for re-deriving step events after leg correction."""

    ankle_rows: list
    rows_by_seq: dict
    calibrations: dict
    foot_contacts_by_seq: dict
    contact_contexts: dict
    fps: float


def _rederive_events_from_corrected_keypoints(step_events, ctx):
    """Re-derive every accepted event's coordinates from the corrected ankle
    rows, keeping its original timing and foot label. Returns
    (refreshed_events, rejected_events)."""
    refreshed_events = []
    rejected_events = []
    prev_proj_by_cam = {}
    for event in sorted(step_events, key=lambda item: int(item["seq_frame"])):
        seq_frame = int(event["seq_frame"])
        row = ctx.rows_by_seq.get(seq_frame)
        if row is None:
            refreshed_events.append(event)
            continue

        foot = str(event.get("foot", row["lower_foot"]))
        ankle_x, ankle_y, ankle_conf = _ankle_for_foot(row, foot)

        cam_idx = int(row["cam"])
        calibration = ctx.calibrations.get(cam_idx) or ctx.calibrations.get(0)
        contact = select_contact_point(
            foot, ankle_x, ankle_y, ankle_conf,
            ctx.foot_contacts_by_seq.get(seq_frame), ctx.contact_contexts.get(cam_idx),
        )
        if not contact["contact_valid"]:
            rejected = dict(event)
            rejected.update({
                "ankle_x": ankle_x, "ankle_y": ankle_y, "ankle_conf": ankle_conf,
                **contact,
            })
            rejected_events.append(rejected)
            continue
        point = (contact["contact_x"], contact["contact_y"])
        track_pos = _project(point, calibration) if calibration else None
        world_x = world_y = None
        if calibration and calibration.get("mode") == "homography":
            world_x, world_y = _transform_homography(point, calibration["homography"])
            step_len_px = None
            prev_proj = prev_proj_by_cam.get(cam_idx)
            step_len_m = None if prev_proj is None else abs(track_pos - prev_proj)
        else:
            prev_proj = prev_proj_by_cam.get(cam_idx)
            step_len_px = None if prev_proj is None or track_pos is None else abs(track_pos - prev_proj)
            mpp = calibration.get("meters_per_pixel") if calibration else None
            step_len_m = None if step_len_px is None or mpp is None else step_len_px * mpp
        if track_pos is not None:
            prev_proj_by_cam[cam_idx] = track_pos

        updated = dict(event)
        updated.setdefault("event_type", "run_step")
        updated.setdefault("flight_start_frame", None)
        updated.setdefault("landing_position_source", "")
        updated.setdefault("landing_score", None)
        updated.update({
            "orig_frame": row["orig_frame"],
            "time_s": row["time_s"],
            "seq_time_s": row["seq_time_s"],
            "cam": row["cam"],
            "ankle_x": ankle_x,
            "ankle_y": ankle_y,
            "ankle_conf": ankle_conf,
            **contact,
            "track_position_px": None if calibration and calibration.get("mode") == "homography" else track_pos,
            "world_x_m": world_x,
            "world_y_m": world_y,
            "step_length_px": step_len_px,
            "step_length_m": step_len_m,
        })
        refreshed_events.append(updated)
    return refreshed_events, rejected_events


def _recover_terminal_preflight_contacts(
    refreshed_events, ctx, terminal_cam, keep_through_seq,
):
    """After a flight is confirmed, run one narrow step-detection pass on the
    terminal camera only up to its last pre-takeoff anchor, appending any valid
    contact the pre-DP pass missed. Mutates refreshed_events in place.

    The initial peak pass happens before DP resolves leg identity, so a valid
    final-camera touchdown immediately before takeoff can be absent from that
    early list even though it is clear in the DP-corrected trajectory. This
    never creates steps during flight or after sand impact.
    """
    terminal_calibration = ctx.calibrations.get(terminal_cam)
    if terminal_calibration is None or keep_through_seq is None:
        return

    terminal_rows = [row for row in ctx.ankle_rows if int(row["cam"]) == terminal_cam]
    existing_terminal_seq = {
        int(event["seq_frame"]) for event in refreshed_events
        if int(event["cam"]) == terminal_cam
    }
    recovered_candidates = detect_steps(terminal_rows, terminal_calibration, fps=ctx.fps)
    for candidate in recovered_candidates:
        seq_frame = int(candidate["seq_frame"])
        row = ctx.rows_by_seq.get(seq_frame)
        if row is None:
            continue
        if seq_frame > int(keep_through_seq) or seq_frame in existing_terminal_seq:
            continue
        foot = str(candidate["foot"])
        ankle_x = float(candidate["ankle_x"])
        ankle_y = float(candidate["ankle_y"])
        ankle_conf = float(candidate["ankle_conf"])
        contact = select_contact_point(
            foot, ankle_x, ankle_y, ankle_conf,
            ctx.foot_contacts_by_seq.get(seq_frame),
            ctx.contact_contexts.get(terminal_cam),
        )
        if not contact["contact_valid"]:
            continue
        recovered = {
            "step_index": 0,
            "seq_frame": seq_frame,
            "orig_frame": int(row["orig_frame"]),
            "time_s": float(row["time_s"]),
            "seq_time_s": float(row["seq_time_s"]),
            "cam": terminal_cam,
            "foot": foot,
            "event_type": "run_step",
            "flight_start_frame": None,
            "landing_position_source": "",
            "landing_score": None,
            "ankle_x": ankle_x,
            "ankle_y": ankle_y,
            "ankle_conf": ankle_conf,
            **contact,
            "track_position_px": None,
            "world_x_m": None,
            "world_y_m": None,
            "step_length_px": None,
            "step_length_m": None,
            "cadence_spm": None,
            "avg_cadence_spm": None,
        }
        recovered["contact_selection_reason"] = (
            f"{contact['contact_selection_reason']};"
            "terminal_preflight_recovered_after_dp"
        )
        refreshed_events.append(recovered)
        existing_terminal_seq.add(seq_frame)


def _drop_terminal_events_after_flight(
    refreshed_events, terminal_cam, keep_through_seq, replace_after_seq,
):
    """A confirmed flight invalidates every ordinary peak after the last
    pre-takeoff contact: peaks before impact are mid-air swing motion, peaks
    after impact are recovery motion. Older fallback detections only provide
    _replace_after_seq, so retain their former post-impact-only behaviour."""
    return [
        event for event in refreshed_events
        if not (int(event["cam"]) == terminal_cam
                and (
                    (keep_through_seq is not None
                     and int(event["seq_frame"]) > int(keep_through_seq))
                    or (keep_through_seq is None and replace_after_seq is not None
                        and int(event["seq_frame"]) >= int(replace_after_seq))
                ))
    ]


def _apply_long_jump_final_landing(refreshed_events, ctx):
    """Detect one terminal-camera long-jump landing and, if found, recover any
    missed pre-takeoff contact, drop mid-air/recovery peaks, and append the
    landing event. Returns the (possibly rebuilt) event list."""
    landing = _detect_long_jump_final_landing(ctx.ankle_rows, refreshed_events, ctx.fps)
    if landing is None:
        return refreshed_events

    terminal_cam = int(landing["cam"])
    _recover_terminal_preflight_contacts(
        refreshed_events, ctx, terminal_cam, landing.get("_keep_through_seq"),
    )
    keep_through_seq = landing.pop("_keep_through_seq", None)
    replace_after_seq = landing.pop("_replace_after_seq", None)
    refreshed_events = _drop_terminal_events_after_flight(
        refreshed_events, terminal_cam, keep_through_seq, replace_after_seq,
    )
    refreshed_events.append(landing)
    return refreshed_events


def _mean_step_length_m(events):
    lengths = [
        float(e["step_length_m"]) for e in events if e.get("step_length_m") is not None
    ]
    return float(np.mean(lengths)) if lengths else None


def _write_refreshed_step_csvs(step_analysis, output_dir, ankle_rows, refreshed_events):
    ankle_csv = step_analysis.get("ankle_csv") or str(Path(output_dir) / "ankle_positions.csv")
    steps_csv = step_analysis.get("steps_csv") or str(Path(output_dir) / "step_events.csv")
    write_csv(ankle_csv, ankle_rows, ANKLE_FIELDS)
    write_csv(steps_csv, refreshed_events, STEP_FIELDS)


def refresh_step_analysis_after_leg_correction(
    step_analysis,
    config,
    output_dir,
    keypoints_npz,
    offsets_npz,
    foot_npz=None,
    meters_per_pixel=None,
):
    """Refresh rows and final contact coordinates after keypoints were rewritten.

    ``run_step_stride_analysis()`` must run before anchor leg correction because it
    provides the touchdown anchors. After ``apply_anchor_leg_correction()`` rewrites
    left/right leg identity in ``keypoints.npz``, the previously computed
    ``ankle_rows`` still reflect the pre-correction labels. This function keeps the
    already accepted event timing/foot labels, but regenerates ankle rows and event
    coordinates from the corrected keypoints so the final overlay and CSVs use one
    consistent source of truth.  Touchdown *time* remains the original
    ankle-peak result.  Its final location follows the contact hierarchy:
    heel (confidence >= .50), big toe (>= .50), then ankle fallback.
    """
    if not step_analysis:
        return step_analysis

    cameras = config.get("cameras") or []
    if not cameras:
        return step_analysis

    fps = _first_camera_video_fps(cameras)
    ankle_rows = load_ankle_positions(keypoints_npz, offsets_npz, fps)
    rows_by_seq = {int(row["seq_frame"]): row for row in ankle_rows}
    foot_npz = foot_npz or str(Path(keypoints_npz).parent / "foot_keypoints.npz")
    foot_contacts_by_seq = load_foot_contact_positions(foot_npz, offsets_npz)
    contact_contexts = _contact_validation_contexts(
        cameras, step_analysis.get("step_events", []), rows_by_seq,
        foot_contacts_by_seq)
    calibrations = _build_sequential_calibrations(cameras, config, meters_per_pixel)
    ctx = _RefreshContext(
        ankle_rows=ankle_rows,
        rows_by_seq=rows_by_seq,
        calibrations=calibrations,
        foot_contacts_by_seq=foot_contacts_by_seq,
        contact_contexts=contact_contexts,
        fps=fps,
    )

    refreshed_events, rejected_events = _rederive_events_from_corrected_keypoints(
        step_analysis.get("step_events", []), ctx,
    )

    if bool(config.get("long_jump_final_landing", False)):
        refreshed_events = _apply_long_jump_final_landing(refreshed_events, ctx)

    refreshed_events.sort(key=lambda event: int(event["seq_frame"]))
    _recompute_contact_event_metrics(refreshed_events, calibrations, contact_contexts)
    # seq_frame is already comparable across cameras (cameras are laid out
    # sequentially along the runway), so refreshed_events above is already in
    # true trial-wide chronological order. Number steps globally instead of
    # resetting per camera, so switching cameras mid-trial (in the burned-in
    # "S{n}" overlay labels and the step_index served to the frontend) keeps
    # counting up instead of restarting at S1.
    for idx, event in enumerate(refreshed_events, start=1):
        event["step_index"] = idx
    avg_cadence_spm = add_global_cadence(refreshed_events, ankle_rows)
    avg_step_length_m = _mean_step_length_m(refreshed_events)

    _write_refreshed_step_csvs(step_analysis, output_dir, ankle_rows, refreshed_events)
    step_analysis["ankle_rows"] = ankle_rows
    step_analysis["step_events"] = refreshed_events
    step_analysis["rejected_step_events"] = rejected_events
    step_analysis["avg_cadence_spm"] = avg_cadence_spm
    step_analysis["avg_step_length_m"] = avg_step_length_m
    return step_analysis


def write_csv(path, rows, fieldnames):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def _draw_dashed_line(img, pt1, pt2, color, thickness=2, dash_len=12, gap_len=8):
    # NOTE: duplicated in core/draw_utils.draw_dashed_line -- kept local here
    # because core/__init__ eagerly imports core.pipeline, which imports this
    # module, so `from core...` here is a circular import.
    dx = pt2[0] - pt1[0]
    dy = pt2[1] - pt1[1]
    length = (dx * dx + dy * dy) ** 0.5
    if length == 0:
        return
    ux, uy = dx / length, dy / length
    pos = 0.0
    drawing = True
    while pos < length:
        seg = dash_len if drawing else gap_len
        end_pos = min(pos + seg, length)
        if drawing:
            x1 = int(pt1[0] + ux * pos)
            y1 = int(pt1[1] + uy * pos)
            x2 = int(pt1[0] + ux * end_pos)
            y2 = int(pt1[1] + uy * end_pos)
            cv2.line(img, (x1, y1), (x2, y2), color, thickness)
        pos = end_pos
        drawing = not drawing


def _draw_track_lines(frame, start_line=None, end_line=None):
    if not start_line and not end_line:
        return

    if start_line and end_line:
        start_a = (int(start_line[0][0]), int(start_line[0][1]))
        start_b = (int(start_line[1][0]), int(start_line[1][1]))
        end_a = (int(end_line[0][0]), int(end_line[0][1]))
        end_b = (int(end_line[1][0]), int(end_line[1][1]))
        quad_edges = [(start_a, end_a), (end_a, end_b), (end_b, start_b), (start_b, start_a)]
        for edge_start, edge_end in quad_edges:
            _draw_dashed_line(frame, edge_start, edge_end, (255, 255, 255), thickness=2)
        cv2.line(frame, start_a, start_b, (0, 0, 0), 5)
        cv2.line(frame, start_a, start_b, (180, 255, 255), 3)
        cv2.line(frame, end_a, end_b, (0, 0, 0), 5)
        cv2.line(frame, end_a, end_b, (255, 200, 100), 3)
    elif start_line:
        line_a = (int(start_line[0][0]), int(start_line[0][1]))
        line_b = (int(start_line[1][0]), int(start_line[1][1]))
        cv2.line(frame, line_a, line_b, (180, 255, 255), 3)
    elif end_line:
        line_a = (int(end_line[0][0]), int(end_line[0][1]))
        line_b = (int(end_line[1][0]), int(end_line[1][1]))
        cv2.line(frame, line_a, line_b, (255, 200, 100), 3)


def _event_contact_display(event):
    """Return final landing point and a distinguishable marker colour."""
    joint = str(event.get("contact_joint") or "ankle")
    x = event.get("contact_x", event.get("ankle_x"))
    y = event.get("contact_y", event.get("ankle_y"))
    if "estimated" in joint:
        return int(x), int(y), (255, 0, 255), "E"    # purple estimated impact
    if "heel" in joint:
        return int(x), int(y), (0, 180, 0), "H"       # green
    if "big_toe" in joint:
        return int(x), int(y), (0, 165, 255), "T"     # orange
    return int(x), int(y), (0, 0, 255), "A"            # red ankle fallback


def render_overlay(
    video_path,
    ankle_rows,
    step_events,
    output_video,
    start_line=None,
    end_line=None,
):
    if not ankle_rows:
        return

    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        raise FileNotFoundError(f"cannot open video: {video_path}")

    width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    fps = cap.get(cv2.CAP_PROP_FPS) or 60.0
    out = cv2.VideoWriter(
        output_video,
        cv2.VideoWriter_fourcc(*"mp4v"),
        fps,
        (width, height),
    )

    events_by_frame = {int(e["orig_frame"]): e for e in step_events}
    event_history = []
    current_pos = 0

    for row in ankle_rows:
        target_frame = int(row["orig_frame"])
        while current_pos <= target_frame:
            ok, frame = cap.read()
            if not ok:
                break
            current_pos += 1

        if not ok:
            break

        _draw_track_lines(frame, start_line=start_line, end_line=end_line)

        rx, ry = int(row["right_ankle_x"]), int(row["right_ankle_y"])
        lx, ly = int(row["left_ankle_x"]), int(row["left_ankle_y"])
        cv2.circle(frame, (rx, ry), 3, (0, 0, 255), -1)
        cv2.circle(frame, (lx, ly), 3, (255, 0, 0), -1)

        event = events_by_frame.get(target_frame)
        if event:
            event_history.append(event)

        for past in event_history[-20:]:
            if past.get("homography_lateral_valid") is False:
                continue
            px, py, colour, joint_tag = _event_contact_display(past)
            cv2.circle(frame, (px, py), 6, TEXT_COLOR, 2)
            cv2.circle(frame, (px, py), 3, colour, -1)
            label = f"S{past['step_index']} {joint_tag}"
            if past["step_length_m"] is not None:
                label += f" L={past['step_length_m']:.2f}m"
            elif past["step_length_px"] is not None:
                label += f" L={past['step_length_px']:.0f}px"
            label_y = py + 43 if (past['step_index'] % 2 == 1) else py + 70
            cv2.putText(frame, label, (px + 8, label_y),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.55, TEXT_COLOR, 2, cv2.LINE_AA)

        cv2.putText(frame, f"Time: {row['time_s']:.2f}s", (30, 40),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.9, TEXT_COLOR, 2, cv2.LINE_AA)
        cv2.putText(frame, f"Steps: {len(event_history)}", (30, 78),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.9, TEXT_COLOR, 2, cv2.LINE_AA)
        out.write(frame)

    cap.release()
    out.release()


def annotate_step_stride_video(
    input_video,
    output_video,
    ankle_rows,
    step_events,
):
    """Draw step length and cadence onto an existing sequential pipeline video."""
    if not ankle_rows:
        return

    cap = cv2.VideoCapture(input_video)
    if not cap.isOpened():
        raise FileNotFoundError(f"cannot open video: {input_video}")

    width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    fps = cap.get(cv2.CAP_PROP_FPS) or 60.0
    out = cv2.VideoWriter(
        output_video,
        cv2.VideoWriter_fourcc(*"mp4v"),
        fps,
        (width, height),
    )

    rows_by_seq = {int(r["seq_frame"]): r for r in ankle_rows}
    events_by_seq = {int(e["seq_frame"]): e for e in step_events}
    event_history_by_cam = {}
    frame_idx = 0

    while True:
        ok, frame = cap.read()
        if not ok:
            break

        row = rows_by_seq.get(frame_idx)
        cam_idx = int(row["cam"]) if row else None
        if row:
            rx, ry = int(row["right_ankle_x"]), int(row["right_ankle_y"])
            lx, ly = int(row["left_ankle_x"]), int(row["left_ankle_y"])
            cv2.circle(frame, (rx, ry), 3, (0, 0, 255), -1)
            cv2.circle(frame, (lx, ly), 3, (255, 0, 0), -1)

        event = events_by_seq.get(frame_idx)
        if event:
            event_cam = int(event["cam"])
            event_history_by_cam.setdefault(event_cam, []).append(event)

        cam_history = event_history_by_cam.get(cam_idx, []) if cam_idx is not None else []
        for past in cam_history[-20:]:
            px, py, colour, joint_tag = _event_contact_display(past)
            cv2.circle(frame, (px, py), 6, TEXT_COLOR, 2)
            cv2.circle(frame, (px, py), 3, colour, -1)
            label = f"S{past['step_index']} {joint_tag}"
            if past["step_length_m"] is not None:
                label += f" L={past['step_length_m']:.2f}m"
            elif past["step_length_px"] is not None:
                label += f" L={past['step_length_px']:.0f}px"
            label_y = py + 43 if (past['step_index'] % 2 == 1) else py + 70
            cv2.putText(frame, label, (px + 8, label_y),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.55, TEXT_COLOR, 2, cv2.LINE_AA)

        if row:
            cv2.putText(frame, f"Time: {row['seq_time_s']:.2f}s", (30, 40),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.9, TEXT_COLOR, 2, cv2.LINE_AA)
        total_steps = sum(len(history) for history in event_history_by_cam.values())
        cv2.putText(frame, f"Steps: {total_steps}", (30, 78),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.9, TEXT_COLOR, 2, cv2.LINE_AA)

        out.write(frame)
        frame_idx += 1

    cap.release()
    out.release()


def run_step_stride_analysis(
    config,
    output_dir=None,
    keypoints_npz=None,
    offsets_npz=None,
    meters_per_pixel=None,
    min_step_frames=None,
    prominence=None,
):
    """Run ankle, step length, and cadence analysis from a pipeline config dict.

    Writes ankle_positions.csv / step_events.csv and returns the analysis dict.
    Rendering the overlay video is the caller's job (see ``render_overlay``).
    """
    cameras = config.get("cameras") or []
    if not cameras:
        raise ValueError("config has no cameras")

    cam_cfg = cameras[0]
    video_path = cam_cfg.get("video_path")
    if not video_path:
        raise ValueError("first camera has no video_path")

    output_dir = output_dir or config.get("output_dir") or str(Path(video_path).resolve().parent)
    stem = Path(video_path).stem
    tracked_stem = f"{stem}_tracked"
    keypoints_npz = keypoints_npz or str(Path(output_dir) / "sequential_tracked" / "input_2D" / "keypoints.npz")
    if not Path(keypoints_npz).exists():
        keypoints_npz = str(Path(output_dir) / tracked_stem / "input_2D" / "keypoints.npz")
    offsets_npz = offsets_npz or str(Path(output_dir) / f"{stem}_offsets.npz")

    if not Path(keypoints_npz).exists():
        raise FileNotFoundError(f"keypoints npz not found: {keypoints_npz}")
    if not Path(offsets_npz).exists():
        raise FileNotFoundError(f"offsets npz not found: {offsets_npz}")

    fps = _video_fps(video_path)
    ankle_rows = load_ankle_positions(keypoints_npz, offsets_npz, fps)
    calibrations = _build_sequential_calibrations(cameras, config, meters_per_pixel)

    step_events = []
    for cam_idx in sorted({int(row["cam"]) for row in ankle_rows}):
        if cam_idx >= len(cameras):
            continue
        cam_rows = [row for row in ankle_rows if int(row["cam"]) == cam_idx]
        next_cam_rows = sorted(
            (row for row in ankle_rows if int(row["cam"]) == cam_idx + 1),
            key=lambda row: int(row["seq_frame"]),
        )
        step_events.extend(detect_steps(
            cam_rows,
            calibrations[cam_idx],
            fps=fps,
            min_step_frames=min_step_frames,
            prominence=prominence,
            lookahead_rows=next_cam_rows[:STEP_DETECTION_LOOKAHEAD_FRAMES],
        ))

    step_events.sort(key=lambda event: int(event["seq_frame"]))
    avg_cadence_spm = add_global_cadence(step_events, ankle_rows)

    ankle_csv = str(Path(output_dir) / f"{stem}_ankle_positions.csv")
    steps_csv = str(Path(output_dir) / f"{stem}_step_events.csv")
    write_csv(ankle_csv, ankle_rows, ANKLE_FIELDS)
    write_csv(steps_csv, step_events, STEP_FIELDS)

    return {
        "ankle_csv": ankle_csv,
        "steps_csv": steps_csv,
        "overlay_video": None,
        "detected_steps": len(step_events),
        "avg_cadence_spm": avg_cadence_spm,
        "avg_step_length_m": _mean_step_length_m(step_events),
        "ankle_rows": ankle_rows,
        "step_events": step_events,
    }


def parse_args():
    parser = argparse.ArgumentParser(
        description="Extract ankle positions, step events, and step length."
    )
    parser.add_argument("--config", help="pipeline YAML config; used to infer paths")
    parser.add_argument("--video", help="original video path")
    parser.add_argument("--keypoints-npz", help="input_2D/keypoints.npz")
    parser.add_argument("--offsets-npz", help="tracking offsets npz")
    parser.add_argument("--output-dir", help="output directory")
    parser.add_argument("--meters-per-pixel", type=float, default=None)
    parser.add_argument("--distance-m", type=float, default=None)
    parser.add_argument("--start-line", nargs=4, type=float, metavar=("X1", "Y1", "X2", "Y2"))
    parser.add_argument("--end-line", nargs=4, type=float, metavar=("X1", "Y1", "X2", "Y2"))
    parser.add_argument("--min-step-frames", type=int, default=None)
    parser.add_argument("--prominence", type=float, default=None)
    parser.add_argument("--make-video", action="store_true")
    parser.add_argument("--output-video", default=None)
    return parser.parse_args()


def main():
    args = parse_args()
    inferred = {}
    cam_cfg = {}
    cfg = {}
    if args.config:
        inferred = _default_paths_from_config(args.config)
        cfg = inferred["config"]
        cam_cfg = inferred["camera"]

    video_path = args.video or inferred.get("video")
    keypoints_npz = args.keypoints_npz or inferred.get("keypoints_npz")
    offsets_npz = args.offsets_npz or inferred.get("offsets_npz")
    output_dir = args.output_dir or inferred.get("output_dir") or "step_output"

    if not video_path or not keypoints_npz or not offsets_npz:
        raise ValueError("provide --config or all of --video, --keypoints-npz, --offsets-npz")

    fps = _video_fps(video_path)

    start_line = _parse_line(args.start_line)
    end_line = _parse_line(args.end_line)
    if start_line is None and cam_cfg.get("start_line"):
        start_line = [(float(x), float(y)) for x, y in cam_cfg["start_line"]]
    if end_line is None and cam_cfg.get("end_line"):
        end_line = [(float(x), float(y)) for x, y in cam_cfg["end_line"]]

    distance_m = args.distance_m
    if distance_m is None:
        distance_m = cam_cfg.get("distance_m") or cfg.get("distance_m")

    calibration = _make_calibration(
        cam_cfg, cfg, args.meters_per_pixel, start_line, end_line, distance_m
    )

    ankle_rows = load_ankle_positions(keypoints_npz, offsets_npz, fps)
    step_events = detect_steps(
        ankle_rows,
        calibration,
        fps=fps,
        min_step_frames=args.min_step_frames,
        prominence=args.prominence,
    )
    avg_cadence_spm = add_cadence(step_events)

    stem = Path(video_path).stem
    ankle_csv = str(Path(output_dir) / f"{stem}_ankle_positions.csv")
    steps_csv = str(Path(output_dir) / f"{stem}_step_events.csv")

    write_csv(ankle_csv, ankle_rows, ANKLE_FIELDS)
    write_csv(steps_csv, step_events, STEP_FIELDS)

    print(f"Ankle positions: {ankle_csv}")
    print(f"Step events: {steps_csv}")
    print(f"Detected steps: {len(step_events)}")
    if avg_cadence_spm is not None:
        print(f"Average cadence: {avg_cadence_spm:.2f} steps/min")
    if calibration["mode"] == "homography":
        print("Distance calibration: homography world coordinates; step_length_m uses world_x_m difference.")
    elif calibration["meters_per_pixel"] is None:
        print("Distance calibration: none; step_length_m is empty, step_length_px is available.")
    else:
        print(f"Distance calibration: {calibration['meters_per_pixel']:.6f} m/px")

    if args.make_video:
        output_video = args.output_video or str(Path(output_dir) / f"{stem}_steps_overlay.mp4")
        render_overlay(
            video_path,
            ankle_rows,
            step_events,
            output_video,
            start_line=start_line,
            end_line=end_line,
        )
        print(f"Overlay video: {output_video}")


if __name__ == "__main__":
    main()
